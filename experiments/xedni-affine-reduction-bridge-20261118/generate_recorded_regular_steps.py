#!/usr/bin/env python3
"""Generate Lean RegularStep witnesses for the frozen rational additions."""

import argparse
from fractions import Fraction
from hashlib import sha256
import json
from pathlib import Path

import run


HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "xedni-known-relation-lifts-20261118" / "run-result.json"
PROTOCOL = HERE / "protocol.json"
OUTPUT = HERE / "RecordedRegularSteps.lean"


def rat_term(value):
    return f"(({value.numerator} : ℚ) / ({value.denominator} : ℚ))"


def generate():
    source_bytes = SOURCE.read_bytes()
    source_hash = sha256(source_bytes).hexdigest()
    protocol = json.loads(PROTOCOL.read_text())
    assert source_hash == protocol["source_sha256"]
    source = json.loads(source_bytes)
    assert source["schema"] == "xedni-known-relation-lifts-result-v1"
    rows = [row for row in source["rows"] if row["status"] == "exact_relation"]
    assert len(rows) == 13
    primes = sorted({row["hit"]["p"] for row in rows})
    lines = [
        "import RationalRegularStep",
        "import CurveEquationCertificates",
        "import Mathlib.Tactic",
        "",
        "set_option maxRecDepth 8192",
        "",
        "/-!",
        "RegularStep witnesses for the 54 rational additions on the thirteen",
        "recorded paths. Generated by `generate_recorded_regular_steps.py` from",
        f"source SHA-256 `{source_hash}`.",
        "-/",
        "",
        "namespace XedniRecordedRegularSteps",
        "",
        "open XedniLocalZModReduction XedniRationalLocalWitness",
        "open XedniRationalCurveBridge XedniRationalRegularStep",
        "open XedniRegularChainReduction XedniAffineReductionBridge",
        "open XedniCoordinateCertificates XedniCurveEquationCertificates",
        "",
    ]
    for p in primes:
        lines.append(f"local instance : Fact (Nat.Prime {p}) := ⟨by norm_num⟩")
    lines.extend([
        "",
        "private theorem int_sub_div_ne_zero (p : ℕ) [Fact (Nat.Prime p)]",
        "    (c a d : ℤ) (hd : (d : ZMod p) ≠ 0)",
        "    (hcross : ((c * d - a : ℤ) : ZMod p) ≠ 0) :",
        "    (c : ZMod p) - (a : ZMod p) / (d : ZMod p) ≠ 0 := by",
        "  intro h",
        "  have heq : (a : ZMod p) = (c : ZMod p) * (d : ZMod p) :=",
        "    (div_eq_iff hd).mp (sub_eq_zero.mp h).symm",
        "  apply hcross",
        "  calc",
        "    ((c * d - a : ℤ) : ZMod p) =",
        "        (c : ZMod p) * (d : ZMod p) - (a : ZMod p) := by push_cast; ring",
        "    _ = 0 := by rw [← heq, sub_self]",
        "",
        "#print axioms int_sub_div_ne_zero",
        "",
    ])
    count = 0
    tangent = 0
    chord = 0
    for row in rows:
        hit = row["hit"]
        p, a, b = hit["p"], hit["a"], hit["b"]
        A, B = row["model"]["A"], row["model"]["B"]
        T = tuple(Fraction(z) for z in row["model"]["T"])
        assert run.on_curve(T, A, B)
        assert run.reduce_point(T, p) == row["R"]
        P = T
        max_multiple = max(abs(a), abs(b))
        for n in range(1, max_multiple):
            Q, branch, data = run.add_rat(P, T, A)
            assert Q is not None and run.on_curve(Q, A, B)
            assert data is not None and all(z.denominator % p for z in (*P, *T, *Q))
            assert run.reduce_point(Q, p) == run.add_mod(
                run.reduce_point(P, p), run.reduce_point(T, p), A, p)
            assert branch == ("tangent" if n == 1 else "chord")
            stem = f"row{row['hit_index']}"
            prior = f"{stem}_m{n}"
            next_point = f"{stem}_m{n + 1}"
            name = f"{stem}_step{n}"
            x, y = P
            tx, ty = T
            qx, qy = Q
            lines.extend([
                f"/-- Row {row['hit_index']}, {n}T + T = {n + 1}T ({branch}). -/",
                f"theorem {name} :",
                f"    RegularStep {prior}_localPoint {stem}_m1_localPoint",
                f"      {next_point}_localPoint := by",
            ])
            if branch == "tangent":
                tangent += 1
                lines.extend([
                    f"  apply tangent_step {p} rfl ({A} : ℚ) {rat_term(x)}",
                    f"    {rat_term(y)} {rat_term(qx)} {rat_term(qy)}",
                    f"  · exact localToRat_integer {p} ({A})",
                    f"  · exact localToRat_fraction {p} _ {prior}_x",
                    f"  · exact localToRat_fraction {p} _ {prior}_y",
                    f"  · exact localToRat_fraction {p} _ {next_point}_x",
                    f"  · exact localToRat_fraction {p} _ {next_point}_y",
                    f"  · change reduceZMod {p}",
                    f"      (2 * toLocal {p} {rat_term(y)} {prior}_y) ≠ 0",
                    "    simp only [map_mul, map_ofNat, reduce_rational]",
                    "    norm_num <;> decide",
                ])
            else:
                chord += 1
                assert tx.denominator == 1
                lines.extend([
                    f"  apply chord_step {p} {rat_term(x)} {rat_term(y)}",
                    f"    {rat_term(tx)} {rat_term(ty)} {rat_term(qx)} {rat_term(qy)}",
                    f"  · exact localToRat_fraction {p} _ {prior}_x",
                    f"  · exact localToRat_fraction {p} _ {prior}_y",
                    f"  · exact localToRat_fraction {p} _ {stem}_m1_x",
                    f"  · exact localToRat_fraction {p} _ {stem}_m1_y",
                    f"  · exact localToRat_fraction {p} _ {next_point}_x",
                    f"  · exact localToRat_fraction {p} _ {next_point}_y",
                    f"  · change reduceZMod {p}",
                    f"      (toLocal {p} {rat_term(tx)} {stem}_m1_x -",
                    f"        toLocal {p} {rat_term(x)} {prior}_x) ≠ 0",
                    "    simp only [map_sub, reduce_rational]",
                    "    norm_num only",
                    f"    change (({tx.numerator} : ℤ) : ZMod {p}) -",
                    f"      (({x.numerator} : ℤ) : ZMod {p}) /",
                    f"        (({x.denominator} : ℤ) : ZMod {p}) ≠ 0",
                    f"    exact int_sub_div_ne_zero {p} ({tx.numerator}) ({x.numerator})",
                    f"      ({x.denominator}) (by norm_num <;> decide)",
                    "      (by norm_num <;> decide)",
                ])
            lines.extend([
                "  · norm_num [addX]",
                "  · norm_num [addY, addX]",
                "",
                f"#print axioms {name}",
                "",
            ])
            P = Q
            count += 1
        stem = f"row{row['hit_index']}"
        chain = "(RegularChain.refl _)"
        for n in range(max_multiple - 1, 0, -1):
            chain = f"(RegularChain.step {stem}_step{n} {chain})"
        lines.extend([
            f"/-- Row {row['hit_index']}, full regular addition path to {max_multiple}T. -/",
            f"theorem {stem}_chain :",
            f"    RegularChain {stem}_m1_localPoint {stem}_m1_localPoint",
            f"      {stem}_m{max_multiple}_localPoint := by",
            f"  exact {chain}",
            "",
            f"#print axioms {stem}_chain",
            "",
        ])
    assert (count, tangent, chord) == (54, 13, 41)
    lines.extend(["end XedniRecordedRegularSteps", ""])
    return "\n".join(lines).encode(), source_hash, count, tangent, chord


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data, source_hash, count, tangent, chord = generate()
    if args.check:
        assert OUTPUT.read_bytes() == data, "generated Lean file differs"
    else:
        OUTPUT.write_bytes(data)
    print(json.dumps({"check": args.check, "steps": count, "tangent": tangent,
                      "chord": chord, "source_sha256": source_hash}, sort_keys=True))


if __name__ == "__main__":
    main()
