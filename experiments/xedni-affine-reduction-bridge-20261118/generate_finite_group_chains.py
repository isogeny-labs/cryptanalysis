#!/usr/bin/env python3
"""Generate finite-field ellipticity and group-chain certificates."""

import argparse
from hashlib import sha256
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "xedni-known-relation-lifts-20261118" / "run-result.json"
PROTOCOL = HERE / "protocol.json"
OUTPUT = HERE / "FiniteGroupChains.lean"


def generate():
    source_bytes = SOURCE.read_bytes()
    source_hash = sha256(source_bytes).hexdigest()
    protocol = json.loads(PROTOCOL.read_text())
    assert source_hash == protocol["source_sha256"]
    source = json.loads(source_bytes)
    assert source["schema"] == "xedni-known-relation-lifts-result-v1"
    rows = [row for row in source["rows"] if row["status"] == "exact_relation"]
    assert len(rows) == 13
    primes = sorted({row["hit"]["p"] for row in rows})
    lines = [
        "import RecordedRegularSteps",
        "import RegularGroupLaw",
        "import Mathlib.Tactic",
        "",
        "/-!",
        "Finite-field ellipticity and group-law consequences for the thirteen",
        "recorded regular chains. Generated by `generate_finite_group_chains.py`",
        f"from source SHA-256 `{source_hash}`.",
        "-/",
        "",
        "namespace XedniFiniteGroupChains",
        "",
        "open XedniLocalZModReduction XedniRegularChainReduction",
        "open XedniRegularGroupLaw XedniRecordedRegularSteps",
        "open XedniCurveEquationCertificates",
        "",
    ]
    for p in primes:
        lines.append(f"local instance : Fact (Nat.Prime {p}) := ⟨by norm_num⟩")
    lines.append("")
    for row in rows:
        hit = row["hit"]
        p, a, b = hit["p"], hit["a"], hit["b"]
        A, B = row["model"]["A"], row["model"]["B"]
        assert A == -1
        delta = -16 * (4 * A**3 + 27 * B**2)
        assert delta % p != 0
        stem = f"row{row['hit_index']}"
        last = max(abs(a), abs(b))
        local_type = f"localIntegers {p}"
        local_a = f"((algebraMap ℤ ({local_type})) ({A}))"
        local_b = f"((algebraMap ℤ ({local_type})) ({B}))"
        f = f"(reduceZMod {p})"
        start = f"{stem}_m1_localPoint"
        end = f"{stem}_m{last}_localPoint"
        lines.extend([
            f"/-- Row {row['hit_index']}: discriminant {delta} is nonzero mod {p}. -/",
            f"theorem {stem}_elliptic :",
            f"    (shortCurve ({A} : ZMod {p}) ({B} : ZMod {p})).IsElliptic := by",
            "  rw [WeierstrassCurve.isElliptic_iff]",
            "  rw [isUnit_iff_ne_zero]",
            "  norm_num [shortCurve, WeierstrassCurve.Δ, WeierstrassCurve.b₂,",
            "    WeierstrassCurve.b₄, WeierstrassCurve.b₆, WeierstrassCurve.b₈] <;> decide",
            "",
            f"local instance {stem}_reduced_elliptic :",
            f"    (shortCurve ({f} {local_a}) ({f} {local_b})).IsElliptic := by",
            f"  simpa [reduce_integer, map_ofNat] using {stem}_elliptic",
            "",
            f"theorem {stem}_group_relation :",
            "    ∃ n : ℕ,",
            f"      toGroupPoint (mapPoint {f} {end}) =",
            f"        toGroupPoint (mapPoint {f} {start}) +",
            f"          n • toGroupPoint (mapPoint {f} {start}) := by",
            f"  exact reduced_regularChain_group_relation {f} {stem}_chain",
            "",
            f"#print axioms {stem}_elliptic",
            f"#print axioms {stem}_reduced_elliptic",
            f"#print axioms {stem}_group_relation",
            "",
        ])
    lines.extend(["end XedniFiniteGroupChains", ""])
    return "\n".join(lines).encode(), source_hash, len(rows), primes


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data, source_hash, rows, primes = generate()
    if args.check:
        assert OUTPUT.read_bytes() == data, "generated Lean file differs"
    else:
        OUTPUT.write_bytes(data)
    print(json.dumps({"check": args.check, "rows": rows, "primes": primes,
                      "source_sha256": source_hash}, sort_keys=True))


if __name__ == "__main__":
    main()
