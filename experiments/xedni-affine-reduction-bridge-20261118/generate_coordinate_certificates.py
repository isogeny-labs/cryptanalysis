#!/usr/bin/env python3
"""Generate Lean denominator certificates from the frozen rational paths."""

import argparse
from fractions import Fraction
from hashlib import sha256
import json
from pathlib import Path

import run


HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "xedni-known-relation-lifts-20261118" / "run-result.json"
PROTOCOL = HERE / "protocol.json"
OUTPUT = HERE / "CoordinateCertificates.lean"


def certificate_lines():
    source_bytes = SOURCE.read_bytes()
    protocol = json.loads(PROTOCOL.read_text())
    source_hash = sha256(source_bytes).hexdigest()
    assert source_hash == protocol["source_sha256"]
    source = json.loads(source_bytes)
    assert source["schema"] == "xedni-known-relation-lifts-result-v1"

    lines = [
        "import RationalLocalWitness",
        "import Mathlib.Tactic",
        "",
        "/-!",
        "Canonical-denominator certificates for every rational coordinate in the",
        "thirteen exact-relation addition paths. Generated by",
        "`generate_coordinate_certificates.py` from the frozen source digest",
        f"`{source_hash}`.",
        "-/",
        "",
        "namespace XedniCoordinateCertificates",
        "",
        "open XedniRationalLocalWitness XedniLocalZModReduction",
        "",
    ]
    count = 0
    paths = 0
    for row in source["rows"]:
        if row["status"] != "exact_relation":
            continue
        paths += 1
        hit = row["hit"]
        p, a, b = hit["p"], hit["a"], hit["b"]
        A, B = row["model"]["A"], row["model"]["B"]
        T = tuple(Fraction(z) for z in row["model"]["T"])
        assert run.on_curve(T, A, B)
        assert run.reduce_point(T, p) == row["R"]
        P = T
        max_multiple = max(abs(a), abs(b))
        for multiple in range(1, max_multiple + 1):
            assert P is not None and run.on_curve(P, A, B)
            for label, coordinate in zip(("x", "y"), P):
                assert coordinate.denominator > 0
                assert coordinate.denominator % p != 0
                name = f"row{row['hit_index']}_m{multiple}_{label}"
                lines.extend([
                    f"/-- Row {row['hit_index']}, {multiple}T, {label}-coordinate. -/",
                    f"theorem {name} :",
                    f"    Admissible {p} (({coordinate.numerator} : ℚ) / "
                    f"({coordinate.denominator} : ℚ)) := by",
                    "  norm_num [Admissible, primeIdeal, Ideal.mem_span_singleton]",
                    f"#print axioms {name}",
                    "",
                ])
                count += 1
            if multiple < max_multiple:
                P, branch, _ = run.add_rat(P, T, A)
                assert branch in ("tangent", "chord")
    assert paths == 13 and count == 134
    lines.extend(["end XedniCoordinateCertificates", ""])
    return "\n".join(lines).encode(), paths, count, source_hash


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data, paths, count, source_hash = certificate_lines()
    if args.check:
        assert OUTPUT.read_bytes() == data, "generated Lean file differs"
    else:
        OUTPUT.write_bytes(data)
    print(json.dumps({"paths": paths, "coordinates": count,
                      "source_sha256": source_hash, "check": args.check}, sort_keys=True))


if __name__ == "__main__":
    main()
