#!/usr/bin/env python3
"""Bound explicit joint-operator resolutions of norm quotients."""

import json
from math import isqrt, log2
from pathlib import Path

from homogeneous_norm_hilbert import semiregular_hilbert_function
from norm_hilbert_resolution_ledger import hilbert_numerator


MODEL_DIMENSIONS = (32, 64, 128, 256)
MODEL_FRACTIONS = ((0, 1), (1, 4), (1, 2), (3, 4), (7, 8))


def resolution_bound(hilbert, operators):
    numerator = hilbert_numerator(hilbert, operators)
    maximum = max(map(abs, numerator))
    total = sum(map(abs, numerator))
    return {
        "operators": operators,
        "largest_absolute_numerator_coefficient": maximum,
        "minimum_free_summands_in_one_shift": maximum,
        "numerator_l1_norm": total,
        "minimum_total_free_summands": total,
    }


def exact_panel(panel):
    variables = panel["projective_section_dimension"]
    hilbert = panel["homogeneous_hilbert_function_through_zero"][:-1]
    return {
        "variables": variables,
        "hilbert_function": hilbert,
        "operator_bounds": [
            resolution_bound(hilbert, operators)
            for operators in range(variables + 1)
        ],
    }


def model_record(hilbert, variables, operators, label):
    bound = resolution_bound(hilbert, operators)
    return {
        "operators": operators,
        "remaining_directions": variables - operators,
        "operator_label": label,
        "log2_one_shift_bound_per_original_variable": (
            log2(bound["minimum_free_summands_in_one_shift"]) / variables
        ),
        "log2_total_bound_per_original_variable": (
            log2(bound["minimum_total_free_summands"]) / variables
        ),
    }


def model_panel(variables):
    hilbert = semiregular_hilbert_function(variables)[:-1]
    records = []
    used = set()
    for numerator, denominator in MODEL_FRACTIONS:
        operators = variables * numerator // denominator
        records.append(model_record(
            hilbert,
            variables,
            operators,
            f"k={numerator}r/{denominator}",
        ))
        used.add(operators)
    remaining = isqrt(variables)
    operators = variables - remaining
    if operators not in used:
        records.append(model_record(
            hilbert,
            variables,
            operators,
            "r-k=floor(sqrt(r))",
        ))
    records.append(model_record(
        hilbert,
        variables,
        variables,
        "k=r",
    ))
    return {"variables": variables, "operator_bounds": records}


def main():
    source = json.loads(
        Path(__file__).with_name("homogeneous_norm_hilbert.json").read_text(
            encoding="utf-8"
        )
    )
    result = {
        "scope": (
            "Hilbert-numerator lower bounds for explicit graded resolutions "
            "over polynomial rings generated by commuting linear operators."
        ),
        "algorithm_claimed": False,
        "exact_panels": [exact_panel(panel) for panel in source["panels"]],
        "semi_regular_model_only": [
            model_panel(variables) for variables in MODEL_DIMENSIONS
        ],
    }
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
