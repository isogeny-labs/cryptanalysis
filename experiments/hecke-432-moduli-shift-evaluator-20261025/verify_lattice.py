"""Independent rational-lattice and unit-choice audit of the shift recipe."""
from fractions import Fraction
from hashlib import sha256
import json
from math import gcd
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    protocol = json.loads((HERE/'protocol.json').read_text())
    result_path = HERE/'result.json'
    result_bytes = result_path.read_bytes()
    result = json.loads(result_bytes)
    assert result['status'] == 'PASS_MODULI_QUARTER_SHIFT_EVALUATOR'
    checks = 0
    for sign in (-1, 1):
        for a in range(-5, 6):
            for b in range(-5, 6):
                for c in range(-5, 6):
                    # L0=<1,4*tau>; adjoining tau+sign/4 yields this coordinate.
                    left = (Fraction(a)+sign*Fraction(c,4), 4*b+c)
                    # In <1,tau+sign/4>, the same point has coefficients a-sign*b,4*b+c.
                    right = (Fraction(a-sign*b)+sign*Fraction(4*b+c,4), 4*b+c)
                    assert left == right
                    checks += 1
    units = [u for u in range(1, 432) if gcd(u, 432) == 1]
    assert len(units) == 144
    for u in units:
        orientation = 1 if u % 4 == 1 else -1
        assert u % 4 in (1, 3)
        for sign in (-1, 1):
            # The subgroup generated by T+sign*R changes only by sign and a lattice period.
            changed = (orientation, Fraction(sign*u,4))
            reference = (orientation, Fraction(sign*orientation,4))
            assert changed[0] == reference[0]
            assert (changed[1]-reference[1]).denominator == 1
    for case in result['cases']:
        assert case['S_order'] == 108
        assert len(case['outputs']) == 2
        assert all(row['subgroup_order'] == 27 for row in case['outputs'])
        assert all(row['plus_same'] and row['minus_same']
                   for row in case['alternate_generator_checks'])
        if case['prime'] % 4 == 3:
            assert case['frobenius_swaps_shift_kernels'] is True
    out = {'status': 'PASS_INDEPENDENT_LATTICE_AND_UNIT_AUDIT',
           'producer_result_sha256': sha256(result_bytes).hexdigest(),
           'rational_lattice_equalities_checked': checks,
           'generator_units_checked': len(units),
           'orientation_checks': 2*len(units),
           'finite_field_cases_replayed': len(result['cases'])}
    (HERE/'validation.json').write_text(json.dumps(out, sort_keys=True, indent=2)+'\n')
    print(json.dumps(out, sort_keys=True))


if __name__ == '__main__':
    main()
