"""Check frozen inputs and internal accounting for the block diagnostic."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
cfg = json.loads((HERE / 'protocol.json').read_text())
result = json.loads((HERE / 'result.json').read_text())
assert result['protocol_sha256'] == hashlib.sha256((HERE / 'protocol.json').read_bytes()).hexdigest()
for name, digest in cfg['sources'].items():
    assert hashlib.sha256(Path(name).read_bytes()).hexdigest() == digest, name
assert result['candidate_id'] is None
assert result['curve_id'] == cfg['curve_id']
assert result['source_codes'] == 281 and result['states_per_slot'] == 1124
assert result['product_subspace_rank'] == 10
rows = result['rows']
assert len(rows) == 1 + cfg['ordinary_residual_count']
assert len({tuple(row['target_point']) for row in rows}) == len(rows)
assert rows[0]['name'] == 'positive_residual'
assert rows[0]['exact_product_subspace_hits'] == 1
assert all(row['exact_product_subspace_hits'] == 0 for row in rows[1:])
assert all(row['name'] == f'public_minus_three_{i}' for i, row in enumerate(rows[1:]))
for row in rows:
    assert len(row['levels']) == len(cfg['free_code_bits'])
    for bit_count, level in zip(cfg['free_code_bits'], row['levels']):
        assert level['free_code_bits'] == bit_count
        assert sum(level['rank_histogram'].values()) == level['blocks']
        assert 0 <= level['rejected_blocks'] <= level['blocks']
        assert 0 <= level['full_rank_blocks'] <= level['blocks']-level['rejected_blocks']
        if row is rows[0]:
            assert level['positive_block_retained'] is True
        else:
            assert level['positive_block_retained'] is None
    assert row['query_seconds_including_all_levels'] > 0
assert 'sorryAx' not in (HERE / 'lean_check.log').read_text()
assert 'depends on axioms' in (HERE / 'lean_check.log').read_text()
receipt = {'status': 'PASS_FROZEN_BLOCK_DIAGNOSTIC_ACCOUNTING',
           'candidate_id': None, 'query_count': len(rows),
           'ordinary_residual_count': cfg['ordinary_residual_count'],
           'input_sha256': {name: digest for name, digest in cfg['sources'].items()},
           'result_sha256': hashlib.sha256((HERE / 'result.json').read_bytes()).hexdigest(),
           'protocol_sha256': result['protocol_sha256'],
           'scope': 'frozen hashes, row and rank accounting, positive retention; arithmetic generated by checked Sage run'}
(HERE / 'verification_result.json').write_text(json.dumps(receipt, indent=2, sort_keys=True)+'\n')
print(json.dumps({'status': receipt['status'], 'query_count': len(rows)}, sort_keys=True))
