#!/usr/bin/env python3
"""Write `figures/result.tex` (pgfplots) from the archived `result.json`.

Lays out the recorded end-to-end cold gaps to the tuned rho rT770 (log axis):
the IC baseline (kP+cP), the known-log arm at K600 and the primary cL220, each
with its 95% interval. REFERENCE ROW: not an IC improvement. No new computation.
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
RUN = HERE / "run_github_39307634508" / "panel" / "result.json"

ROWS = [("e2e_cold_gap_kP_cP_over_rT", "IC baseline\\\\kP+cP"),
        ("e2e_cold_gap_cL600_over_rT", "known-log K600\\\\cL600"),
        ("primary_gap_cL220_over_rT", "known-log K220\\\\cL220 (primary)")]


def main():
    s = json.loads(RUN.read_text())["statistics"]
    pts, labels = [], []
    for i, (key, name) in enumerate(ROWS):
        v = s[key]
        lo, hi = v["ci95"]
        e = v["estimate"]
        pts.append("(%d,%.4f) += (0,%.4f) -= (0,%.4f)" % (i, e, hi - e, e - lo))
        labels.append("{%s}" % name)
    tex = r"""\documentclass[border=6pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage{pgfplots}
\pgfplotsset{compat=1.16}
%% Generated by make_result_figure.py from run_github_39307634508/panel/result.json.
\begin{document}
\begin{tikzpicture}
\begin{axis}[width=13cm, height=7cm, ymode=log, ymin=0.8, ymax=120, xmin=-0.5, xmax=3.1,
  ylabel={end-to-end cold: mean / mean cold(rT770)},
  xtick={0,1,2}, xticklabels={%(labels)s}, x tick label style={font=\footnotesize, align=center},
  grid=major, grid style={gray!20}, font=\small, log ticks with fixed point, ytick={1,2,5,10,20,50,100}]
\addplot[only marks, mark=*, mark size=2.6pt, blue!70!black, error bars/.cd, y dir=both, y explicit,
  error bar style={thick, blue!70!black}] coordinates {%(pts)s};
\draw[red!80!black, thick] (axis cs:-0.5,1) -- (axis cs:3.1,1) node[pos=0.12, above, font=\footnotesize] {rho = 1};
\node[font=\footnotesize, anchor=south west] at (axis cs:0.05,61.35) {61.4 [53.3, 71.3]};
\node[font=\footnotesize, anchor=south west] at (axis cs:1.05,8.54) {8.54 [7.46, 9.88]};
\node[font=\footnotesize, anchor=south west] at (axis cs:2.05,2.19) {2.19 [1.86, 2.59]};
\end{axis}
\end{tikzpicture}
\end{document}
""" % {"labels": ",".join(labels), "pts": " ".join(pts)}
    (HERE / "figures" / "result.tex").write_text(tex)
    print(HERE / "figures" / "result.tex")


if __name__ == "__main__":
    main()
