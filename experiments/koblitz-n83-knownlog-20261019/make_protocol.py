def text(record):
    return json.dumps(record, indent=1, sort_keys=True) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        frozen = json.loads(OUT.read_text())["frozen_at_utc"]
        if OUT.read_text() != text(build(frozen)):
            raise SystemExit("protocol.json differs from the rebuilt protocol")
        print("protocol_verified=" + str(OUT))
        return
    OUT.write_text(text(build(datetime.now(timezone.utc).isoformat(timespec="seconds"))))
    print(str(OUT))


if __name__ == "__main__":
    main()
