//! Known-log factor base for the n = 83, a = 1 Koblitz curve (K_1 over GF(2^83)).
//!
//! Usage: `knownlog_base <columns> <seed> <base_header_out.jsonl> <factor_log_table_out.json>`
//!
//! Writes a `point_defined_factor_base` header in B's layout (the retained
//! base header the rank-probe producer reads) and the matching
//! `compact_orbit_factor_log_table` (the `KIC_LOG_TABLE_IN` file):
//!
//! * scalars a_0, a_1, ... : splitmix64 seeded with `seed`, each output
//!   rejection-sampled below floor(2^64 / r) * r and reduced mod r; 0 is
//!   rejected. The base of K columns uses the first K scalars, so a smaller
//!   base is a prefix of a larger one with the same seed.
//! * representatives R_j = [a_j]G (fixed-base comb over [2^i]G, one batched
//!   inversion per comb row);
//! * points, column by column, s = 0..82: phi^s(R_j) with label
//!   [j, lambda^s mod r], then -phi^s(R_j) with label [j, -lambda^s mod r]
//!   (B's order, checked against B's K600 header);
//! * logs[j] = a_j, so no rank stage and no linear algebra is needed (`LAnone`).
//!
//! Every orbit must be distinct (no R_j in the signed-Frobenius orbit of an
//! earlier R_i); the generator asserts it. Its own clock runs from the start
//! of `main` until both files are written and synced, and it prints one JSON
//! line with that time and its phases. No dependencies: the field, the curve
//! and SHA-256 are written out here.

use std::collections::HashSet;
use std::fs::File;
use std::io::Write;
use std::time::Instant;

const MASK: u128 = (1u128 << 83) - 1;
/// Prime order of the subgroup generated by G.
const R: u64 = 8_569_786_107_849_059;
/// Eigenvalue of the Frobenius phi on <G>: phi(P) = [LAMBDA]P.
const LAMBDA: u64 = 2_998_004_823_950_457;
/// G in the polynomial basis of GF(2)[x] / (x^83 + x^7 + x^4 + x^2 + 1), as integers.
const GX: u128 = 6_614_244_651_398_184_860_292_015;
const GY: u128 = 8_868_260_410_029_249_391_539_529;
/// y^2 + xy = x^3 + A x^2 + B.
const A: u128 = 1;
const B: u128 = 1;

type Point = Option<(u128, u128)>;

fn mul(a: u128, b: u128) -> u128 {
    // carry-less product of two degree <= 82 polynomials, then reduction
    let (mut lo, mut hi) = (0u128, 0u128);
    let mut bb = b;
    let mut i = 0u32;
    while bb != 0 {
        if bb & 1 == 1 {
            lo ^= a << i;
            if i > 0 {
                hi ^= a >> (128 - i);
            }
        }
        bb >>= 1;
        i += 1;
    }
    reduce(lo, hi)
}

fn reduce(lo: u128, hi: u128) -> u128 {
    // x^83 = x^7 + x^4 + x^2 + 1
    let t = (lo >> 83) | (hi << 45);
    let v = (lo & MASK) ^ t ^ (t << 2) ^ (t << 4) ^ (t << 7);
    let t2 = v >> 83;
    (v & MASK) ^ t2 ^ (t2 << 2) ^ (t2 << 4) ^ (t2 << 7)
}

fn sqr(a: u128) -> u128 {
    mul(a, a)
}

fn inv(a: u128) -> u128 {
    // a^(2^83 - 2) = prod_{i=1..82} a^(2^i)
    assert!(a != 0, "inverse of zero");
    let mut power = a;
    let mut result = 1u128;
    for _ in 1..83 {
        power = sqr(power);
        result = mul(result, power);
    }
    result
}

fn on_curve(p: Point) -> bool {
    match p {
        None => true,
        Some((x, y)) => {
            let x2 = sqr(x);
            sqr(y) ^ mul(x, y) == mul(x2, x) ^ mul(A, x2) ^ B
        }
    }
}

fn neg(p: Point) -> Point {
    p.map(|(x, y)| (x, x ^ y))
}

fn double(p: Point) -> Point {
    let (x, y) = p?;
    if x == 0 {
        return None;
    }
    let l = x ^ mul(y, inv(x));
    let x3 = sqr(l) ^ l ^ A;
    let y3 = sqr(x) ^ mul(l ^ 1, x3);
    Some((x3, y3))
}

fn add(p: Point, q: Point) -> Point {
    let (x1, y1) = match p {
        None => return q,
        Some(v) => v,
    };
    let (x2, y2) = match q {
        None => return p,
        Some(v) => v,
    };
    if x1 == x2 {
        return if y1 == y2 { double(p) } else { None };
    }
    let l = mul(y1 ^ y2, inv(x1 ^ x2));
    let x3 = sqr(l) ^ l ^ x1 ^ x2 ^ A;
    let y3 = mul(l, x1 ^ x3) ^ x3 ^ y1;
    Some((x3, y3))
}

fn scalar_mul(p: Point, k: u64) -> Point {
    let mut acc: Point = None;
    for bit in (0..64).rev() {
        acc = double(acc);
        if (k >> bit) & 1 == 1 {
            acc = add(acc, p);
        }
    }
    acc
}

fn mulmod(a: u64, b: u64) -> u64 {
    ((a as u128 * b as u128) % R as u128) as u64
}

struct SplitMix64(u64);

impl SplitMix64 {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }
}

/// The first `count` scalars of the seeded stream (see the module comment).
fn scalars(seed: u64, count: usize) -> Vec<u64> {
    let limit = (u64::MAX / R) * R;
    let mut rng = SplitMix64(seed);
    let mut out = Vec::with_capacity(count);
    while out.len() < count {
        let v = rng.next();
        if v >= limit {
            continue;
        }
        let a = v % R;
        if a != 0 {
            out.push(a);
        }
    }
    out
}

/// R_j = [a_j]G for every scalar: comb over D_i = [2^i]G (r < 2^53), with
/// the additions of one comb row sharing one inversion (Montgomery's trick).
fn representatives(scalars_in: &[u64]) -> Vec<(u128, u128)> {
    let bits = 64 - R.leading_zeros();
    let mut table: Vec<(u128, u128)> = Vec::with_capacity(bits as usize);
    let mut d: Point = Some((GX, GY));
    for _ in 0..bits {
        table.push(d.expect("[2^i]G is affine"));
        d = double(d);
    }
    let mut acc: Vec<Point> = vec![None; scalars_in.len()];
    for (i, &(dx, dy)) in table.iter().enumerate() {
        let mut members = Vec::new();
        for (j, &a) in scalars_in.iter().enumerate() {
            if (a >> i) & 1 == 1 {
                match acc[j] {
                    None => acc[j] = Some((dx, dy)),
                    Some((x, _)) if x == dx => acc[j] = add(acc[j], Some((dx, dy))),
                    Some(_) => members.push(j),
                }
            }
        }
        if members.is_empty() {
            continue;
        }
        // prefix products of the denominators x_j + dx, one inversion, back substitution
        let dens: Vec<u128> = members.iter().map(|&j| acc[j].unwrap().0 ^ dx).collect();
        let mut prefix = Vec::with_capacity(dens.len());
        let mut running = 1u128;
        for &v in &dens {
            running = mul(running, v);
            prefix.push(running);
        }
        let mut inverse = inv(running);
        for k in (0..members.len()).rev() {
            let before = if k == 0 { 1u128 } else { prefix[k - 1] };
            let inv_k = mul(inverse, before);
            inverse = mul(inverse, dens[k]);
            let j = members[k];
            let (x1, y1) = acc[j].unwrap();
            let l = mul(y1 ^ dy, inv_k);
            let x3 = sqr(l) ^ l ^ x1 ^ dx ^ A;
            let y3 = mul(l, x1 ^ x3) ^ x3 ^ y1;
            acc[j] = Some((x3, y3));
        }
    }
    acc.into_iter().map(|p| p.expect("a_j is nonzero mod r, so R_j is affine")).collect()
}

// ── SHA-256 (FIPS 180-4), for the base hash ──
