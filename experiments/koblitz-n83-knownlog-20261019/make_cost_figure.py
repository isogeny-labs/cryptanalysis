#!/usr/bin/env python3
"""Write `figures/cost_model.tex` (pgfplots) from `analysis/cost_model.json`.

Lays out the recorded model curves only (no new computation): predicted
end-to-end cold cost of a known-log base against K, models A and B, with the
frozen K_opt and K600 marked and the archived tuned-rho mean cold time as a
reference line. A prediction, not a measurement.
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    model = json.loads((HERE / "analysis" / "cost_model.json").read_text())
    c = model["constants"]
    k_opt = model["K_opt"]
    curves = {}
    for name in ("A", "B"):
        curves[name] = " ".join("(%s,%.4f)" % (k, v / 1000) for k, v in
                                sorted(model["models"][name]["curve_ms"].items(), key=lambda kv: int(kv[0])))
    rho = c["rho_mean_cold_ms"] / 1000
    a_opt = model["models"]["A"]["cost_ms_at_K_opt"] / 1000
    a_600 = model["models"]["A"]["cost_ms_at_K600"] / 1000
    tex = r"""\documentclass[border=6pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage{pgfplots}
\pgfplotsset{compat=1.16}
%% Generated by make_cost_figure.py from analysis/cost_model.json. Prediction, not a measurement.
\begin{document}
\begin{tikzpicture}
\begin{axis}[width=13cm, height=7.5cm, xlabel={orbit columns $K$}, ylabel={predicted end-to-end cold (s)},
  ymode=log, xmin=100, xmax=900, ymin=1, ymax=250, grid=both, grid style={gray!20},
  ytick={1,2,3,5,10,20,50,100}, log ticks with fixed point,
  legend style={at={(0.02,0.98)}, anchor=north west, font=\footnotesize}, font=\small]
\addplot[thick, blue] coordinates {%(A)s};
\addlegendentry{model A: archived run 39214027289 constants, probe law $r/(166\cdot 83K^2)$}
\addplot[thick, dashed, orange!80!black] coordinates {%(B)s};
\addlegendentry{model B: A with the local K220/K600 per-state and per-probe exponents}
\addplot[thick, red!80!black, domain=100:900, samples=2] {%(rho).4f};
\addlegendentry{archived rT770 mean cold (%(rho).2f s, 20 points)}
\addplot[only marks, mark=*, mark size=2.2pt, black] coordinates {(%(kopt)d,%(aopt).4f) (600,%(a600).4f)};
\node[anchor=south west, font=\footnotesize] at (axis cs:%(kopt)d,%(aopt).4f) {K$_\mathrm{opt}$=%(kopt)d: %(aopt).2f s};
\node[anchor=south west, font=\footnotesize] at (axis cs:600,%(a600).4f) {K600: %(a600).2f s};
\end{axis}
\end{tikzpicture}
\end{document}
""" % {"A": curves["A"], "B": curves["B"], "rho": rho, "kopt": k_opt, "aopt": a_opt, "a600": a_600}
    (HERE / "figures" / "cost_model.tex").write_text(tex)
    print(HERE / "figures" / "cost_model.tex")


if __name__ == "__main__":
    main()
