#!/usr/bin/env python3
"""Reproducible source-local adaptation; refuses drift in replacement anchors."""
from pathlib import Path
import hashlib
import json

HERE=Path(__file__).resolve().parent
SOURCE=HERE.parent/"pdp-scaling/boolean_f5b_native.cpp"


def generate(out):
    original=SOURCE.read_text()
    text=original
    def replace(left,right,count=1):
        nonlocal text
        if text.count(left)!=count:raise ValueError(f"source anchor count differs: {left[:80]!r}")
        text=text.replace(left,right)
    replace('    int n, universe, words, signature_limit, completion_seed_limit;',
            '    int n, universe, words, signature_limit, completion_seed_limit;\n'
            '    mutable uint64_t criterion_calls=0, criterion_hits=0, normal_zero_outputs=0, signature_zero_pairs=0, product_rows=0, product_nnz=0;\n'
            '    mutable int max_materialized_degree=0;')
    left='''        // Rank order is degree-compatible; the leading term has max degree.
        int rank = lead_rank(p);
        return rank < 0 ? 0 : __builtin_popcount(mask_by_rank[rank]);'''
    right='''        int result=0;
        for(int wi=0;wi<words;++wi){uint64_t x=p.w[wi];while(x){int bit=__builtin_ctzll(x);result=std::max(result,__builtin_popcount(mask_by_rank[wi*64+bit]));x&=x-1;}}
        return result;'''
    replace(left,right)
    replace('''        return r;
    }
    bool multiply_bounded''','''        ++product_rows; product_nnz+=terms(r); max_materialized_degree=std::max(max_materialized_degree,degree(r));
        return r;
    }
    bool multiply_bounded''')
    replace('''        return rem;
    }''','''        if(zero(rem))++normal_zero_outputs;
        return rem;
    }''',2)
    replace('''        if (s.idx >= (int)rewrites.size() || rewrites[s.idx].empty()) return false;
        return syzygies[s.idx][s.mon] || rewrites[s.idx][s.mon] > num;''','''        ++criterion_calls;
        if (s.idx >= (int)rewrites.size() || rewrites[s.idx].empty()) return false;
        bool result=syzygies[s.idx][s.mon] || rewrites[s.idx][s.mon] > num;
        criterion_hits+=result;
        return result;''')
    replace('if(zero(c.poly)){index_syzygy(c.sig);continue;}',
            'if(zero(c.poly)){++signature_zero_pairs;index_syzygy(c.sig);continue;}')
    start=text.index('#ifndef BOOLEAN_F5B_NO_MAIN')
    text=text[:start]+'''int main(){
    std::ios::sync_with_stdio(false);
    int n,g,limit,seed_limit;
    if(!(std::cin>>n>>g>>limit>>seed_limit)||n<1||n>12)return 2;
    Engine e(n,limit,seed_limit);
    for(unsigned i=0;i<unsigned(e.universe);++i){unsigned mask;std::cin>>mask;if(mask>=unsigned(e.universe))return 3;e.mask_by_rank[i]=mask;e.rank_by_mask[mask]=i;}
    std::vector<Poly> F;
    for(int i=0;i<g;++i){int k;std::cin>>k;Poly p;for(int j=0;j<k;++j){uint32_t m;std::cin>>m;uint32_t r=e.rank_by_mask[m];p.w[r>>6]^=uint64_t(1)<<(r&63);}e.max_materialized_degree=std::max(e.max_materialized_degree,e.degree(p));F.push_back(p);}
    auto B=e.basis(F);
    std::cout<<"OK "<<B.size()<<" "<<e.insertions<<" "<<e.reductions<<" "<<e.pairs_processed<<" "<<e.criterion_calls<<" "<<e.criterion_hits<<" "<<e.normal_zero_outputs<<" "<<e.signature_zero_pairs<<" "<<e.product_rows<<" "<<e.product_nnz<<" "<<e.max_materialized_degree<<"\\n";
    for(auto&p:B){auto ms=e.masks(p);std::sort(ms.begin(),ms.end());std::cout<<ms.size();for(auto m:ms)std::cout<<" "<<m;std::cout<<"\\n";}
}
'''
    with out.open('x') as f:f.write('// Generated by generate_native_orders.py; original SHA-256 '+hashlib.sha256(original.encode()).hexdigest()+'\n'+text)
    return {"original_sha256":hashlib.sha256(original.encode()).hexdigest(),
            "generated_sha256":hashlib.sha256(out.read_bytes()).hexdigest()}


if __name__=='__main__':
    import sys
    print(json.dumps(generate(Path(sys.argv[1]))))
