def digest(x):
    return hashlib.sha256(json.dumps(x, sort_keys=True, separators=(",", ":")).encode()).hexdigest()

def point(P):
    return [P.x, P.y, P.inf]

def dump(name, x):
    (HERE / name).write_text(json.dumps(x, indent=2, sort_keys=True) + "\n")

def curve(n, b):
    F = GF2n(n)
    E = Curve(F, b)
    full = [INF]
    for x in range(1 << n):
        P = E.lift_x(x)
        if P is not None:
            full.append(P)
            if E.neg(P) != P:
                full.append(E.neg(P))
    fac = factorint(len(full))
    r = int(max(fac))
    if r <= 2 or fac[r] != 1:
        raise ValueError(json.dumps({"n":n,"b":b,"full_group_order":len(full),"factorization":{str(k):int(v) for k,v in fac.items()},"reason":"no simple largest odd-prime subgroup admitted by frozen protocol"}))
    h = len(full) // r
    G = next(Q for P in full[1:] if not (Q := scalar_mul(E, P, h)).inf)
    assert scalar_mul(E, G, r) == INF
    subgroup = [INF]
    for _ in range(1, r):
        subgroup.append(E.add(subgroup[-1], G))
    assert len(set(subgroup)) == r and E.add(subgroup[-1], G) == INF
    rec = {"field": {"characteristic": 2, "degree": n, "representation": "polynomial_basis", "modulus": F.mod, "element_encoding": "integer coefficient bit vector"},
           "curve": {"model": "y^2+xy=x^3+a2*x^2+a6", "a2": 0, "a6": b, "order": len(full), "subgroup_order": r, "cofactor": h, "generator": point(G), "target_group": "prime-order subgroup generated by G"}}
    cid = f"EC1N{n}Cb{b}h{digest(rec)[:12]}"
    return E, subgroup, full, {"curve_id": cid, **rec, "factorization": {str(k): int(v) for k,v in fac.items()}}

def exact_labels(E, subgroup, ell, multiplier):
    r = len(subgroup)
    V = {E.F.mul(multiplier, x) for x in range(1 << ell)}
    fb = [k for k, P in enumerate(subgroup) if k and P.x in V]
    witnesses = {}
    multiplicity = [0] * r
    count = 0
    for a, b, c in itertools.product(fb, repeat=3):
        k = (a + b + c) % r
        multiplicity[k] += 1
        witnesses.setdefault(k, [a, b, c])
        count += 2
    # Exhaustive independent elliptic-curve witness replay for every positive label.
    for k, abc in witnesses.items():
        assert E.sum([subgroup[a] for a in abc]) == subgroup[k]
    assert sum(multiplicity) == len(fb)**3
    # m-sum DP independently confirms the entire support, including negatives.
    reach = {0}
    for _ in range(3):
        reach = {(a+b) % r for a in reach for b in fb}
    assert reach == set(witnesses)
    return fb, witnesses, multiplicity, count

def feats(E, P, n, ell, mult, b, B):
    return [int((P.x >> i) & 1) for i in range(13)] + [E.F.trace(E.F.mul(E.F.pow(2,i), P.x)) for i in range(8)] + [n, ell, mult, b, B]

def split(n,b,ell,mult):
    if n == 13: return "new-size"
    if b in (3,5): return "new-curve"
    if mult == 2: return "new-base"
    if ell == 4: return "calibration"
    return "train"

def metrics(y, p, threshold):
    reject = p < threshold
    pos = y == 1
    fn = int((reject & pos).sum())
    return {"targets": len(y), "positives": int(pos.sum()), "rejected": int(reject.sum()), "false_negatives": fn,
            "true_negatives": int((reject & ~pos).sum()), "false_negative_rate": fn/max(1,int(pos.sum())),
            "negative_rejection_fraction": int((reject & ~pos).sum())/max(1,int((~pos).sum())),
            "safe_rejection_proved": False}

def search_kernel(fb, r, kernel):
    """Instrument scalar additions, equality tests and hash probes explicitly."""
    ops = {"setup_scalar_additions": 0, "setup_hash_probes": 0, "online_scalar_additions": 0,
           "online_hash_probes": 0, "online_equality_tests": 0, "sort_comparison_upper_bound": 0}
    t0 = time.process_time()
    pair = None
    if kernel != "ordered-exhaustive":
        pair = []
        for a, b in itertools.product(fb, repeat=2):
            pair.append((a+b)%r)
            ops["setup_scalar_additions"] += 1
        if kernel == "pair-index":
            ops["setup_hash_probes"] = len(pair)
            pair = set(pair)
        else:
            ops["sort_comparison_upper_bound"] = len(pair) * max(0, math.ceil(math.log2(max(1,len(pair)))))
            pair = sorted(set(pair))
    setup = time.process_time()-t0
    t0 = time.process_time()
    out=[]
    for k in range(1,r):
        found=False
        if kernel == "ordered-exhaustive":
            for a,b,c in itertools.product(fb, repeat=3):
                ops["online_scalar_additions"] += 2
                ops["online_equality_tests"] += 1
                if (a+b+c)%r == k:
                    found=True
                    break
        else:
            for a in fb:
                q=(k-a)%r
                ops["online_scalar_additions"]+=1
                if kernel == "pair-index":
                    ops["online_hash_probes"]+=1
                    found=q in pair
                else:
                    lo,hi=0,len(pair)
                    while lo<hi:
                        mid=(lo+hi)//2
                        ops["online_equality_tests"]+=1
                        if pair[mid]<q:lo=mid+1
                        else:hi=mid
                    ops["online_equality_tests"]+=1
                    found=lo<len(pair) and pair[lo]==q
                if found:break
        out.append(int(found))
    online=time.process_time()-t0
    return out,{"kernel":kernel,"operation_counts":ops,"setup_cpu_seconds":setup,"online_cpu_seconds":online,
                "unit_weight_count":sum(ops.values()),"note":"scalar arithmetic and probe counts are a toy kernel objective, not group operations or a full IC cost"}

def main():
    if (HERE/"prefilter-results.json").exists():
        raise SystemExit("Append-only run already exists; choose a fresh run directory.")
    protocol=json.loads((HERE/"PROTOCOL.json").read_text())
    sources=[Path(__file__),HERE/"PROTOCOL.json",HERE/"AMENDMENT-01.json",HERE/"AMENDMENT-02.json",ROOT/"experiments/pdp-scaling/gf2n.py",ROOT/"experiments/pdp-scaling/target_fiber.py"]
    manifest={"argv":sys.argv,"started_utc":time.strftime("%Y-%m-%dT%H:%M:%SZ",time.gmtime()),"source_sha256":{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sources},
              "hardware":{"platform":platform.platform(),"python":sys.version,"cpus":os.cpu_count(),"gpu":{"devices":[]},"F4_F2_ECHELON":os.getenv("F4_F2_ECHELON"),"performance_tier":"unqualified exploratory CPU container"},"protocol_sha256":digest(protocol)}
    dump("prefilter-launch.json",manifest)
    t0=time.process_time()
    rows=[];cells=[];cache={};admission_failures=[]
    with (HERE/"prefilter-inputs.jsonl").open("x") as inputs:
        for n in protocol["prefilter"]["curves"]["degrees"]:
            for b in protocol["prefilter"]["curves"]["b"]:
                try:E,sub,full,rec=curve(n,b)
                except ValueError as exc:
                    admission_failures.append(json.loads(str(exc)));continue
                cache[n,b]=(E,sub,full,rec)
                for base in protocol["prefilter"]["bases"]:
                    ell,mult=base["ell"],base["multiplier"]
                    fb,witness,mults,labelops=exact_labels(E,sub,ell,mult)
                    cid=digest({"curve":rec,"ell":ell,"multiplier":mult,"m":3,"fb_scalars":fb})
                    inputs.write(json.dumps({"cell_sha256":cid,"curve":rec,"ell":ell,"multiplier":mult,"factor_base_scalars":fb,"factor_base_points":[point(sub[k]) for k in fb],"subgroup_points":[point(P) for P in sub],"multiplicity":mults,"positive_witnesses":witness},sort_keys=True)+"\n")
                    tr={E.F.trace(P.x) for P in sub[1:]}
                    row={"cell_sha256":cid,"curve_id":rec["curve_id"],"n":n,"b":b,"ell":ell,"multiplier":mult,"r":len(sub),"h":rec["curve"]["cofactor"],"actual_usable_points":len(fb),"split":split(n,b,ell,mult),"positive_targets":sum(v>0 for v in mults[1:]),"nonidentity_targets":len(sub)-1,"trace_values_subgroup":sorted(tr),"ordered_tuple_count":sum(mults),"label_scalar_additions":labelops,"all_positive_witnesses_group_replayed":True,"independent_support_dp_agreed":True}
                    cells.append(row)
                    for k,P in enumerate(sub[1:],1):
                        rows.append({"cell_sha256":cid,"split":row["split"],"scalar":k,"x":P.x,"label":int(mults[k]>0),"features":feats(E,P,n,ell,mult,b,len(fb))})
    labeltime=time.process_time()-t0
    dump("prefilter-cells.json",cells)
    dump("prefilter-admission-failures.json",admission_failures)
    with (HERE/"prefilter-dataset.jsonl").open("x") as f:
        for row in rows:f.write(json.dumps(row,sort_keys=True)+"\n")
    train=[x for x in rows if x["split"]=="train"]
    X=np.array([x["features"] for x in train]);y=np.array([x["label"] for x in train])
    results=[]
    fitted={}
    for name,model in [("all-accept",None),("decision-tree-depth-4-balanced",DecisionTreeClassifier(max_depth=4,class_weight="balanced",random_state=20261018)),("random-forest-32-depth-6-balanced",RandomForestClassifier(n_estimators=32,max_depth=6,class_weight="balanced",random_state=20261018,n_jobs=1))]:
        t=time.process_time()
        if model is not None:model.fit(X,y)
        train_seconds=time.process_time()-t
        fitted[name]=model
        for part in ["train","calibration","new-curve","new-base","new-size"]:
            rs=[x for x in rows if x["split"]==part]
            xx=np.array([x["features"] for x in rs]);yy=np.array([x["label"] for x in rs])
            t=time.process_time()
            pp=np.ones(len(rs)) if model is None else model.predict_proba(xx)[:,list(model.classes_).index(1)] if 1 in model.classes_ else np.zeros(len(rs))
            infer=time.process_time()-t
            for threshold in protocol["prefilter"]["thresholds"]:
                results.append({"model":name,"split":part,"threshold":threshold,"train_cpu_seconds":train_seconds,"inference_cpu_seconds":infer,**metrics(yy,pp,threshold)})
    dump("prefilter-results.json",{"cells":len(cells),"targets":len(rows),"training_targets":len(train),"training_label_counts":{str(k):int((y==k).sum()) for k in [0,1]},"label_and_feature_cpu_seconds":labeltime,"results":results,"oracle_integration":"disabled; classifier is a diagnostic, not a necessary condition","peak_rss_bytes":resource.getrusage(resource.RUSAGE_SELF).ru_maxrss*1024})
    # Restricted program search; holdout is not examined until selection is fixed.
    searchrows=[];selected=None;t=time.process_time()
    for phase,n,b in [("train",7,1),("heldout",11,3)]:
        E,sub,full,rec=cache[n,b]
        candidates=itertools.product([1,2,3,5,7],["ordered-exhaustive","pair-index","sorted-pair"])
        if phase=="heldout":candidates=[(selected["multiplier"],selected["kernel"]),(1,"pair-index")]
        for mult,kernel in candidates:
            fb,witness,mults,labelops=exact_labels(E,sub,3,mult)
            labels,measurement=search_kernel(fb,len(sub),kernel)
            truth=[int(x>0) for x in mults[1:]]
            assert labels==truth
            row={"phase":phase,"curve_id":rec["curve_id"],"r":len(sub),"ell":3,"multiplier":mult,"actual_usable_points":len(fb),"ordered_tuples":sum(mults),"positive_support_nonidentity":sum(truth),"semantic_replay_all_targets":True,**measurement}
            searchrows.append(row)
        if phase=="train":
            # Enforce matched actual base cardinality when selecting a predicate.
            B0=next(x["actual_usable_points"] for x in searchrows if x["multiplier"]==1)
            matched=[x for x in searchrows if x["actual_usable_points"]==B0]
            selected=min(matched,key=lambda x:(x["unit_weight_count"],x["multiplier"],x["kernel"]))
            dump("program-selected-before-heldout.json",{"selected":selected,"selection":"minimum setup+online counted kernel work among matched usable-base cardinalities","training_rows_sha256":digest(searchrows)})
    dump("program-results.json",{"rows":searchrows,"total_search_and_holdout_cpu_seconds":time.process_time()-t,"total_counted_candidate_work":sum(x["unit_weight_count"] for x in searchrows),"compiler_cost":"none; Python interprets fixed grammar, startup outside reported per-candidate CPU intervals","not_measured":["complete IC pipeline","rho comparator","LLM search","compiled decomposition kernels"],"selected":selected})
    print(json.dumps({"cells":len(cells),"targets":len(rows),"search_candidates":len(searchrows),"label_feature_cpu_seconds":labeltime}))

if __name__=="__main__": main()
