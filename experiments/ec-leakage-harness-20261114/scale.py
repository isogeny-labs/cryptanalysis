#!/usr/bin/env python3
"""Learning curves for generic predictors of k from f(k) = x([k]P).

Follow-up 3 trained its generic learners on 1,000 samples per curve.  This
script asks whether more data changes the answer: for 3 curves per class
(the first three of each class in results/followup_population.json, whose
orders were SEA-computed and BSGS-cross-checked), it draws 1.1 million
samples, keeps the last 100,000 as a fixed test set, and trains on the first
1e3, 1e4, 1e5 and 1e6.

Targets (all functions of x, since x determines k* = min(k, n - k)):
  bit0   lowest bit of k*
  bithi  bit nb-3 of k* (a high bit with both labels common)
  cmod2  c mod 2, c = min(k* mod q, -k* mod q); on smooth curves q | n and
         Pohlig-Hellman computes c exactly, so a learner that found the
         structure would reach accuracy 1.

Learners: least-squares linear classifier and gradient boosting
(HistGradientBoostingClassifier) on bits of x, x mod m (m = 2..32), the
Legendre symbol of x and x/p.

Null: the test labels are independent of anything trained, so under "no
leakage" the test accuracy of the fitted classifier is binomial with mean
mu = pi*a + (1 - pi)*(1 - a), where pi is the test prevalence of label 1 and
a the fraction the classifier predicts as 1.  z = (acc - mu) / sqrt(mu(1-mu)/n).

Samples are generated by PARI (ellmul) and 1,000 per curve are re-derived
with the harness's own Python arithmetic.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import random
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ec_leakage as L  # noqa: E402

OUT = os.path.join(HERE, "results")
SIZES = (1_000, 10_000, 100_000, 1_000_000)
N_TEST = 100_000
MODS = range(2, 33)


def draw(pari, c, n_total, seed):
    pari(f"setrand({seed}); E=ellinit([{c['a']},{c['b']}],{c['p']}); G=[{c['P'][0]},{c['P'][1]}];")
    v = pari(f"my(n={c['n']}); vector({n_total},i,my(k=1+random(n-1)); [k, lift(ellmul(E,G,k)[1])])")
    arr = np.array([[int(t[0]), int(t[1])] for t in v], dtype=np.int64)
    return arr[:, 0], arr[:, 1]


def features(x, p):
    nb = p.bit_length()
    bits = ((x[:, None] >> np.arange(nb)) & 1).astype(np.float32)
    mods = np.stack([x % m for m in MODS], axis=1).astype(np.float32)
    e = (p - 1) // 2
    leg = np.array([1.0 if pow(int(v), e, p) == 1 else -1.0 for v in x], dtype=np.float32)[:, None]
    frac = (x / p).astype(np.float32)[:, None]
    return np.hstack([bits, mods, leg, frac])


def null_z(pred, y):
    pi = float(y.mean())
    a = float(pred.mean())
    mu = pi * a + (1 - pi) * (1 - a)
    acc = float((pred == y).mean())
    return acc, mu, (acc - mu) / math.sqrt(mu * (1 - mu) / len(y))


def fit_linear(F, y, Ft):
    mu, sd = F.mean(0), F.std(0) + 1e-9
    A = np.hstack([(F - mu) / sd, np.ones((len(F), 1), np.float32)])
    w, *_ = np.linalg.lstsq(A, 2.0 * y - 1.0, rcond=None)
    B = np.hstack([(Ft - mu) / sd, np.ones((len(Ft), 1), np.float32)])
    return (B @ w > 0).astype(np.int64)


def fit_hgb(F, y, Ft, seed):
    from sklearn.ensemble import HistGradientBoostingClassifier
    clf = HistGradientBoostingClassifier(max_iter=300, learning_rate=0.1, max_leaf_nodes=63,
                                         early_stopping=len(F) > 10_000, random_state=seed)
    clf.fit(F, y)
    return clf.predict(Ft).astype(np.int64)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--per-class", type=int, default=3)
    ap.add_argument("--max-train", type=int, default=SIZES[-1])
    args = ap.parse_args()
    import cypari2
    pari = cypari2.Pari()
    pari.allocatemem(1 << 31)
    pop = json.load(open(os.path.join(OUT, "followup_population.json")))
    sizes = [s for s in SIZES if s <= args.max_train]
    rows = []
    for kind in ("smooth", "anomalous", "prime"):
        curves = [c for c in pop["curves"] if c["kind"] == kind][: args.per_class]
        for c in curves:
            t0 = time.time()
            n, p, q = c["n"], c["p"], c["q"]
            k, x = draw(pari, c, sizes[-1] + N_TEST, c["seed"])
            E = L.Curve(p, c["a"], c["b"])
            chk = random.Random(c["seed"]).sample(range(len(k)), 1000)
            assert all(E.mul(int(k[i]), tuple(c["P"]))[0] == int(x[i]) for i in chk)
            ks = np.minimum(k, n - k)
            nb = n.bit_length()
            cls = np.minimum(ks % q, (-ks) % q)
            targets = {"bit0": ks & 1, "bithi": (ks >> (nb - 3)) & 1, "cmod2": cls % 2}
            F = features(x, p)
            Ft = F[-N_TEST:]
            ph = None
            if kind == "smooth":
                sub = range(len(k) - N_TEST, len(k) - N_TEST + 2000)
                Pt = tuple(c["P"])
                ph = float(np.mean([L.ph_residue(E, Pt, n, q, int(x[i])) % 2 == cls[i] % 2 for i in sub]))
            for tname, y in targets.items():
                yt = y[-N_TEST:]
                for s in sizes:
                    for lname in ("linear", "hgb"):
                        t1 = time.time()
                        pred = (fit_linear(F[:s], y[:s], Ft) if lname == "linear"
                                else fit_hgb(F[:s], y[:s], Ft, c["seed"]))
                        acc, mu, z = null_z(pred, yt)
                        rows.append({"kind": kind, "idx": c["idx"], "q": q, "q_divides_n": c["q_divides_n"],
                                     "target": tname, "train": s, "learner": lname, "accuracy": acc,
                                     "null_mean": mu, "z": z, "fit_seconds": time.time() - t1,
                                     "ph_accuracy_cmod2": ph if tname == "cmod2" else None})
                        print(f"[{kind} {c['idx']}] {tname:5} n={s:>7} {lname:6} acc {acc:.4f} "
                              f"null {mu:.4f} z {z:+.2f}", file=sys.stderr, flush=True)
            print(f"[{kind} {c['idx']}] done in {time.time() - t0:.0f}s", file=sys.stderr, flush=True)
            json.dump({"sizes": sizes, "n_test": N_TEST, "rows": rows},
                      open(os.path.join(OUT, "scale.json"), "w"), indent=1)
    zs = np.array([r["z"] for r in rows])
    summ = {"fits": len(rows), "max_z": float(zs.max()), "min_z": float(zs.min()),
            "frac_abs_z_gt_3": float((np.abs(zs) > 3).mean()),
            "familywise_p_max_z": float(min(1.0, len(zs) * 0.5 * math.erfc(zs.max() / math.sqrt(2))))}
    for s in sizes:
        zz = np.array([r["z"] for r in rows if r["train"] == s])
        summ[f"train_{s}"] = {"mean_z": float(zz.mean()), "sd_z": float(zz.std(ddof=1)), "max_z": float(zz.max())}
    json.dump({"sizes": sizes, "n_test": N_TEST, "summary": summ, "rows": rows},
              open(os.path.join(OUT, "scale.json"), "w"), indent=1)
    plot(rows, sizes)
    print(json.dumps(summ, indent=1))


def plot(rows, sizes):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    tg = ("bit0", "bithi", "cmod2")
    fig, axes = plt.subplots(1, 3, figsize=(10, 3.2), sharey=True)
    cols = {"smooth": "#4C72B0", "anomalous": "#C44E52", "prime": "#55A868"}
    for ax, t in zip(axes, tg):
        for kind, col in cols.items():
            for lname, mk in (("linear", "o--"), ("hgb", "s-")):
                R = [r for r in rows if r["target"] == t and r["kind"] == kind and r["learner"] == lname]
                if not R:
                    continue
                zm = [np.mean([r["z"] for r in R if r["train"] == s]) for s in sizes]
                ax.plot(sizes, zm, mk, color=col, ms=3, lw=1,
                        label=f"{kind} {lname}" if t == "bit0" else None)
        ax.axhspan(-2, 2, color="0.9")
        ax.set_xscale("log")
        ax.set_title(t, fontsize=9)
        ax.set_xlabel("training samples")
    axes[0].set_ylabel("z vs no-leakage null (mean over curves)")
    axes[0].legend(fontsize=6)
    fig.suptitle("Generic learners vs training-set size (test set 100k)", fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "scale.png"), dpi=70)


if __name__ == "__main__":
    main()
