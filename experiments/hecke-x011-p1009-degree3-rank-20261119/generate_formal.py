"""Generate the Lean quartic root-count theorem from the frozen audited result."""
from pathlib import Path
import hashlib
import json

HERE = Path(__file__).resolve().parent
raw = (HERE / "result.json").read_bytes()
result = json.loads(raw)
post = json.loads((HERE / "post-run.json").read_text())
audit = json.loads((HERE / "audit.json").read_text())
assert hashlib.sha256(raw).hexdigest() == post["producer_result_sha256"] == audit["result_sha256"]
assert audit["status"] == "PASS"
rows = result["source_records"]
assert len(rows) == 84 and [r["source"] for r in rows] == list(range(84))
counts = [r["rational_root_count"] for r in rows]
assert counts.count(1) == 56 and counts.count(4) == 28
lines = [
    "-- Generated by generate_formal.py from the frozen, independently audited result.",
    "-- Quartic coefficients are canonical residues modulo 1009, increasing degree.",
    "set_option maxRecDepth 100000", "set_option maxHeartbeats 0",
    "namespace X011P1009Degree3", "structure Quartic where", "  c0 : Nat",
    "  c1 : Nat", "  c2 : Nat", "  c3 : Nat", "  c4 : Nat",
    "def quartics : List Quartic := [",
]
for i, r in enumerate(rows):
    a, b, c, d, e = r["quartic"]
    lines.append(f"  {{ c0 := {a}, c1 := {b}, c2 := {c}, c3 := {d}, c4 := {e} }}" + ("," if i < 83 else ""))
lines += [
    "]", "def rootCount (q : Quartic) : Nat :=",
    "  ((List.range 1009).filter fun x =>",
    "    (q.c0 + q.c1*x + q.c2*x*x + q.c3*x*x*x + q.c4*x*x*x*x) % 1009 == 0).length",
    "theorem exact_root_counts : quartics.map rootCount = [",
    "  " + ", ".join(map(str, counts)) + "] := by decide",
    "theorem root_count_histogram :",
    "    ((quartics.map rootCount).filter (· == 1)).length = 56 ∧",
    "    ((quartics.map rootCount).filter (· == 4)).length = 28 := by",
    "  rw [exact_root_counts]", "  decide",
    "#print axioms X011P1009Degree3.exact_root_counts",
    "#print axioms X011P1009Degree3.root_count_histogram",
    "end X011P1009Degree3", "",
]
(HERE / "formal" / "Degree3RootCounts.lean").write_text("\n".join(lines))
