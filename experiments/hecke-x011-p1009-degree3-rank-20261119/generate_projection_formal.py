"""Generate a Lean check of the F17 subgroup-projection null vector."""
from pathlib import Path
import gzip
import hashlib
import json

HERE = Path(__file__).resolve().parent
protocol = json.loads((HERE / "protocol.json").read_text())
result_raw = (HERE / "result.json").read_bytes()
result = json.loads(result_raw)
audit = json.loads((HERE / "audit.json").read_text())
projection_raw = (HERE / "projection.json").read_bytes()
projection = json.loads(projection_raw)
witness_raw = (HERE / "rank-witness.json").read_bytes()
witness = json.loads(witness_raw)
assert audit["status"] == "PASS"
assert hashlib.sha256(result_raw).hexdigest() == audit["result_sha256"]
assert hashlib.sha256(projection_raw).hexdigest() == audit["projection_sha256"]
assert hashlib.sha256(witness_raw).hexdigest() == audit["rank_witness_sha256"]
assert len(projection["vector"]) == 84 and any(projection["vector"])
hecke = [{int(k): int(v) for k, v in r["row"].items()}
         for r in result["source_records"] if r["status"] == "CLASS_CLOSED"]
prev = HERE.parent / "hecke-x011-p1009-degree2-rank-20261119"
packed = (prev / "direct-rows.jsonl.gz").read_bytes()
assert hashlib.sha256(packed).hexdigest() == protocol["degree2_direct_rows_gzip_sha256"]
direct = [dict(zip(r["indices"], r["coefficients"]))
          for r in (json.loads(s) for s in gzip.decompress(packed).splitlines())]
rows = hecke + direct
assert len(hecke) == 28 and len(direct) == 568 and len(rows) == projection["checked_rows"]
gain_index = next(i for i, r in enumerate(result["source_records"])
                  if r["source"] == witness["gain_source"] and r["status"] == "CLASS_CLOSED")
gain_index = sum(r["status"] == "CLASS_CLOSED" for r in result["source_records"][:gain_index])
assert {str(k): v for k, v in sorted(hecke[gain_index].items())} == witness["gain_row"]
lines = [
    "-- Generated by generate_projection_formal.py from the audited F17 projection.",
    "set_option maxRecDepth 100000", "set_option maxHeartbeats 0",
    "namespace X011P1009Degree3", "def projectionVector : List Int := [",
    "  " + ", ".join(map(str, projection["vector"])) + "]",
    "def relationRows : List (List (Nat × Int)) := [",
]
for i, row in enumerate(rows):
    terms = ", ".join(f"({k}, {v})" for k, v in sorted(row.items()))
    lines.append(f"  [{terms}]" + ("," if i < len(rows) - 1 else ""))
lines += [
    "]", "def qqKernel : List Int := [",
    "  " + ", ".join(map(str, witness["direct_kernel"])) + "]",
    "def dot (r : List (Nat × Int)) : Int :=",
    "  r.foldl (fun a kv => a + kv.2 * projectionVector.getD kv.1 0) 0",
    "def qqDot (r : List (Nat × Int)) : Int :=",
    "  r.foldl (fun a kv => a + kv.2 * qqKernel.getD kv.1 0) 0",
    "theorem projection_nonzero : projectionVector.any (· != 0) = true := by decide",
    "theorem relation_count : relationRows.length = 596 := by decide",
    "theorem every_relation_annihilates_projection :",
    "    relationRows.all (fun r => dot r % 17 == 0) = true := by decide",
    "theorem qq_kernel_nonzero : qqKernel.any (· != 0) = true := by decide",
    "theorem all_direct_rows_annihilate_qq_kernel :",
    "    (relationRows.drop 28).all (fun r => qqDot r == 0) = true := by decide",
    f"theorem degree3_row_breaks_qq_kernel : qqDot (relationRows.getD {gain_index} []) = 5 := by decide",
    "#print axioms X011P1009Degree3.projection_nonzero",
    "#print axioms X011P1009Degree3.relation_count",
    "#print axioms X011P1009Degree3.every_relation_annihilates_projection",
    "#print axioms X011P1009Degree3.qq_kernel_nonzero",
    "#print axioms X011P1009Degree3.all_direct_rows_annihilate_qq_kernel",
    "#print axioms X011P1009Degree3.degree3_row_breaks_qq_kernel",
    "end X011P1009Degree3", "",
]
(HERE / "formal" / "ProjectionKernel.lean").write_text("\n".join(lines))
