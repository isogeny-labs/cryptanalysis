"""Run a `.sage` script the way `sage FILE.sage ARGS` runs it, without Sage (local check only).

What `sage FILE.sage ARGS` does, and what this module reproduces:

1. The preparser rewrites FILE.sage into FILE.sage.py next to it (the archived tracebacks of
   run 39526183111 name `arm_n2x.sage.py`). The rewrites that matter for these scripts are
   Sage's literal and operator rules: every integer literal n becomes `Integer(n)`, every
   float literal becomes `RealNumber('x')`, `^` becomes `**` and `^^` becomes `^`. This
   module applies exactly those, token by token (`tokenize`), so strings and comments are
   untouched, as Sage's preparser leaves them.
2. FILE.sage.py runs as `__main__` with `sys.argv = [FILE.sage.py] + ARGS`.
3. Inside it, `preparse(text)` is the same rewrite applied to a string, and `load(path)`
   preparses a `.sage` file (or reads a `.py` file) and executes it in the caller's globals:
   the namespace of `__main__`, shared with every file it loads. That shared namespace is
   what v1 got wrong (v3 arm.sage rebinds the module global `_argv`).

Everything else Sage provides (GF, matrix, ZZ, PolyBoRi, ...) is a permissive stand-in that
records its name: the option path of the scripts under test runs no Sage arithmetic, and the
test asserts which stand-ins were touched. This is not Sage; the pinned-image check is the
workflow's `Sage option-path check` step (the same scripts under the real `sage`).
"""
import builtins
import io
import os
import sys
import tokenize
import types


class Integer:
    """Stand-in for sage.rings.integer.Integer (not an int subclass, like Sage's)."""
    __slots__ = ('v',)

    def __init__(self, v=0):
        self.v = int(v)

    def __int__(self):
        return self.v

    def __index__(self):
        return self.v

    def __hash__(self):
        return hash(self.v)

    def __repr__(self):
        return repr(self.v)

    __str__ = __repr__

    def __bool__(self):
        return self.v != 0

    def _o(self, o):
        return o.v if isinstance(o, Integer) else o

    def __eq__(self, o):
        return self.v == self._o(o)

    def __ne__(self, o):
        return self.v != self._o(o)

    def __lt__(self, o):
        return self.v < self._o(o)

    def __le__(self, o):
        return self.v <= self._o(o)

    def __gt__(self, o):
        return self.v > self._o(o)

    def __ge__(self, o):
        return self.v >= self._o(o)

    def __neg__(self):
        return Integer(-self.v)

    def __abs__(self):
        return Integer(abs(self.v))


def _binop(name, swap=False):
    op = getattr(int, name)

    def f(self, o):
        o = o.v if isinstance(o, Integer) else o
        if not isinstance(o, int):
            return NotImplemented
        r = op(self.v, o)
        return Integer(r) if isinstance(r, int) else r
    return f


for _n in ('add', 'sub', 'mul', 'floordiv', 'mod', 'pow', 'lshift', 'rshift', 'and', 'or', 'xor'):
    setattr(Integer, '__%s__' % _n, _binop('__%s__' % _n))
    setattr(Integer, '__r%s__' % _n, _binop('__r%s__' % _n))


def RealNumber(s):
    return float(s)


def preparse_file(text, name):
    """Sage's preparse_file layout: a 5-line header, then the body with hoisted constants.

        # This file was *autogenerated* from the file NAME
        from sage.all_cmdline import *   # import sage library
        <blank>
        _sage_const_1 = Integer(1); _sage_const_0 = Integer(0); ...
        <blank>

    so FILE.sage line L is FILE.sage.py line L + 5, as in run 39526183111's tracebacks
    (arm_n2x.sage line 102 -> arm_n2x.sage.py line 107).
    """
    hoist = {}
    body = preparse(text, hoist)
    consts = '; '.join('%s = %s' % kv for kv in hoist.items())
    return ('# This file was *autogenerated* from the file %s\n'
            'from sage.all_cmdline import *   # import sage library\n\n%s\n\n' % (name, consts)) + body


def _const_name(s, is_float):
    return '_sage_const_' + s.replace('.', 'p').replace('-', 'n').replace('+', '')


def preparse(text, hoist=None):
    """Sage's literal and operator rewrites (integer, float, ^, ^^), applied token by token.

    With `hoist` (a dict), literals become the names `_sage_const_<n>` that preparse_file
    binds once at the top of FILE.sage.py, as Sage's preparse_file does; without it (Sage's
    `preparse(string)`), they are inline `Integer(n)` / `RealNumber('x')`.
    """
    out = []
    toks = list(tokenize.generate_tokens(io.StringIO(text).readline))
    i = 0
    while i < len(toks):
        t = toks[i]
        if t.type == tokenize.NUMBER and not t.string.lower().endswith(('j', 'r')):
            s = t.string
            body = s.replace('_', '')
            is_float = ('.' in body or ('e' in body.lower() and not body.lower().startswith('0x')))
            new = "RealNumber('%s')" % s if is_float else 'Integer(%s)' % s
            if hoist is not None:
                name = _const_name(s, is_float)
                hoist.setdefault(name, new)
                new = name
            out.append((t.type, new, t.start, t.end, t.line))
        elif t.type == tokenize.NUMBER:   # raw literal 1r -> plain int
            out.append((t.type, t.string[:-1], t.start, t.end, t.line))
        elif t.type == tokenize.OP and t.string == '^':
            nxt = toks[i + 1] if i + 1 < len(toks) else None
            if nxt is not None and nxt.type == tokenize.OP and nxt.string == '^' and nxt.start == t.end:
                out.append((t.type, '^', t.start, nxt.end, t.line))
                i += 1
            else:
                out.append((t.type, '**', t.start, t.end, t.line))
        else:
            out.append(tuple(t))
        i += 1
    return tokenize.untokenize([(a, b) for a, b, *_ in out])


class _Stand:
    """Permissive stand-in for any Sage object; every use is recorded by name."""

    def __init__(self, name, log):
        object.__setattr__(self, '_name', name)
        object.__setattr__(self, '_log', log)

    def __getattr__(self, k):
        return _Stand(self._name + '.' + k, self._log)

    def __call__(self, *a, **k):
        self._log.add(self._name + '()')
        return _Stand(self._name + '()', self._log)

    def __repr__(self):
        return '<stand-in %s>' % self._name


class _Builtins(dict):
    """Python builtins, plus a recorded stand-in for any name Sage's namespace would supply."""

    def __init__(self, log):
        super().__init__(vars(builtins))
        self.log = log

    def __missing__(self, k):
        self.log.add(k)
        return _Stand(k, self.log)


class _SageModuleStub(types.ModuleType):
    def __getattr__(self, k):
        if k.startswith('__'):
            raise AttributeError(k)
        return _Stand(self.__name__ + '.' + k, set())


class Result:
    def __init__(self, exc, namespace, stand_ins, argv_seen):
        self.exc, self.namespace, self.stand_ins, self.argv_seen = exc, namespace, stand_ins, argv_seen


def run_sage_file(path, args):
    """`sage PATH ARGS` emulated: returns Result(exc or None, the __main__ globals, stand-ins used)."""
    path = os.path.abspath(path)
    log = set()
    g = {'__name__': '__main__', '__file__': path + '.py', '__builtins__': _Builtins(log),
         'Integer': Integer, 'RealNumber': RealNumber, 'preparse': preparse}

    def load(p, *rest):
        p = str(p)
        text = open(p).read()
        code = preparse_file(text, os.path.basename(p)) if p.endswith('.sage') else text
        exec(compile(code, p + ('.py' if p.endswith('.sage') else ''), 'exec'), g)

    g['load'] = load
    saved_argv, saved_path, saved_mods = list(sys.argv), list(sys.path), dict(sys.modules)
    for m in ('sage', 'sage.rings', 'sage.rings.polynomial', 'sage.rings.polynomial.pbori',
              'sage.rings.polynomial.pbori.pbori', 'sage.all', 'sage.all_cmdline'):
        sys.modules.setdefault(m, _SageModuleStub(m))
    sys.argv = [path + '.py'] + [str(a) for a in args]
    argv_seen = list(sys.argv)
    exc = None
    try:
        code = compile(preparse_file(open(path).read(), os.path.basename(path)), path + '.py', 'exec')
        exec(code, g)
    except BaseException as e:  # SystemExit included: the caller inspects it
        exc = e
    finally:
        sys.argv, sys.path[:] = saved_argv, saved_path
        for m in list(sys.modules):
            if m not in saved_mods:
                del sys.modules[m]
    return Result(exc, g, sorted(log), argv_seen)
