template<unsigned K>
inline uint32_t twice_distance(uint32_t x) {
    const uint32_t rotated = ((x << K) & prime) | (x >> (31 - K));
    return __builtin_popcount(x ^ rotated);
}

template<unsigned K>
inline uint32x4_t twice_distance(uint32x4_t x) {
    const auto rotated = vorrq_u32(vandq_u32(vshlq_n_u32(x, K), vdupq_n_u32(prime)),
                                   vshrq_n_u32(x, 31 - K));
    const auto byte_counts = vcntq_u8(vreinterpretq_u8_u32(veorq_u32(x, rotated)));
    return vpaddlq_u16(vpaddlq_u8(byte_counts));
}

inline uint32_t corrected_reciprocal(uint32_t x) {
    const unsigned total = twice_distance<1>(x) + 23 * twice_distance<9>(x) + 5 * twice_distance<13>(x);
    return multiply(reverse_field_bits(x), corrections[(total >> 1) & 63]);
}

inline uint32x4_t corrected_reciprocal(uint32x4_t x) {
    auto total = vmlaq_n_u32(twice_distance<1>(x), twice_distance<9>(x), 23);
    total = vmlaq_n_u32(total, twice_distance<13>(x), 5);
    uint32_t slots[4];
    vst1q_u32(slots, vandq_u32(vshrq_n_u32(total, 1), vdupq_n_u32(63)));
    for (auto& slot : slots) slot = corrections[slot];
    return multiply(reverse_field_bits(x), vld1q_u32(slots));
}
