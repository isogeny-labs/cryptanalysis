"""Rebuild the public M31 fixture and timing evidence from pinned Git objects."""
import csv
from decimal import Decimal, ROUND_CEILING
import hashlib
import io
import json
from pathlib import Path
import subprocess

directory = Path(__file__).resolve().parent
commit = "9a1d8a6cf4158197c06b0782f833d4626931ebff"
root = "experiments/prime-field-auxiliary-ic/"
panel = root + "snapshot/algebraic/optimized/results/field31_s5_base0/"
public_path = panel + "public.json"
billion = 10**9


def read(path):
    return subprocess.check_output(["git", "-C", directory, "show", f"{commit}:{path}"])


def audited(method, seed):
    prefix = f"benchmarks/records/20261115T0646Z-prime31-retro-{method}-seed{seed}"
    manifest = json.loads(read(prefix + ".json"))
    if manifest["id"] != prefix.split("/")[-1]:
        raise ValueError(f"Wrong manifest identity: {prefix}")
    inputs = {}
    for entry in manifest["raw"]:
        path = entry["path"]
        data = read(path)
        if len(data) != entry["bytes"] or hashlib.sha256(data).hexdigest() != entry["sha256"]:
            raise ValueError(f"Raw evidence mismatch: {path}")
        inputs[path] = data
    label = {"v2-batch": "v2_batch", "rho": "rho"}[method]
    result = json.loads(inputs[f"{panel}{label}_seed{seed}.audited.json"], parse_float=Decimal)
    if result["seed"] != seed or result["label"] != label:
        raise ValueError(f"Wrong audited run: {prefix}")
    return result, inputs[public_path], len(inputs)


def ceiling_ns(seconds):
    return int((seconds * billion).to_integral_value(rounding=ROUND_CEILING))


def lean_pairs(pairs):
    return "[" + ", ".join(f"({a},{b})" for a, b in pairs) + "]"


public = read(public_path)
fixture_data = json.loads(public)
archived = fixture_data["factor_base"]
fixture = read(root + "m31-four-coverage/base71-points.csv").decode()
points = [list(map(int, row)) for row in csv.reader(io.StringIO(fixture))]
bounds = []
runs = []
for seed in range(3):
    ic, ic_public, ic_count = audited("v2-batch", seed)
    rho, rho_public, rho_count = audited("rho", seed)
    if ic_public != public or rho_public != public:
        raise ValueError(f"Unequal public fixture: seed {seed}")
    wall, basis, setup, total = (ic[k] for k in (
        "process_wall_seconds", "basis_seconds", "setup_seconds", "end_to_end_seconds"))
    if abs(total - (wall + basis)) >= Decimal("1e-12") or not (0 <= setup <= wall and basis >= 0):
        raise ValueError(f"Inconsistent accounting: seed {seed}")
    removed = basis + setup
    bounds.append((int(total * billion), ceiling_ns(basis) + ceiling_ns(setup)))
    runs.append(dict(seed=seed, cold_s=str(total), basis_s=str(basis), setup_s=str(setup),
                     removable_percent=str(100 * removed / total),
                     speedup_if_removed=str(total / (total - removed)),
                     rho_cold_s=str(rho["end_to_end_seconds"]),
                     verified_raw_entries=dict(ic=ic_count, rho=rho_count)))

evidence = dict(commit=commit, public_sha256=hashlib.sha256(public).hexdigest(), runs=runs)
(directory / "archive-accounting.json").write_text(json.dumps(evidence, indent=2) + "\n")
declarations = ["-- Generated by replay-archive-check.py.", "namespace M31ArchiveData", ""]
for name, data in [("archived", archived), ("public71", points), ("timingBounds", bounds)]:
    declarations.extend([f"def {name} : List (Nat × Nat) := {lean_pairs(data)}", ""])
declarations.append("end M31ArchiveData")
(directory / "ArchiveData.lean").write_text("\n".join(declarations) + "\n")

# The original pre-lift abscissae are also used to check terminal separation.
roots = fixture_data["structured_roots"]
if len(roots) != 32 or any(type(x) is not int or not 0 <= x < 2**31 - 1 for x in roots):
    raise ValueError("Invalid structured root list")
(directory / "ArchiveRoots.lean").write_text(
    "-- Generated by replay-archive-check.py.\nnamespace M31ArchiveRoots\n"
    + "def roots : List Nat := [" + ", ".join(map(str, roots)) + "]\nend M31ArchiveRoots\n")
