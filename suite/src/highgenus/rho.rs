//! Pollard rho with distinguished points on any [`JacobianGroup`].
//!
//! Solves `Q = k·P` in a subgroup of known prime order `N`. `r`-adding walk
//! (`r` precomputed steps `a_j P + b_j Q`), the negation map on the quotient
//! by `±1` when the group supplies a representative choice (fruitless
//! 2-cycles are escaped by a doubling step), and a distinguished-point
//! table keyed by the hash of the representative. Several independent walks
//! run in sequence from random starts; the first collision between
//! distinct walks (or within one) that yields `b ≠ b'` gives
//! `k = (a − a')/(b' − b) mod N`, which is **verified** by `[k]P = Q`
//! before being returned. Costs are reported in group operations, taken
//! from the group's own counter.
//!
//! This is a reference solver for the higher-genus engines; it is not the
//! tuned prime-field `rho.negation_v5` of `crypto`, and makes no speed claim.

use std::collections::HashMap;

use num_bigint::BigUint;
use num_integer::Integer;
use num_traits::{One, Zero};
use rand::rngs::StdRng;
use rand::{RngCore, SeedableRng};

use super::{HgError, JacobianGroup};

/// Parameters of the walk.
#[derive(Clone, Debug)]
pub struct RhoParams {
    /// Number of precomputed branches.
    pub branches: usize,
    /// Distinguished-point rate `2^-dp_bits`.
    pub dp_bits: u32,
    /// Use the negation map (walk on classes modulo `±1`).
    pub negation_map: bool,
    /// Give up after this many group operations (0 = `64·sqrt(N)` guard).
    pub max_ops: u64,
    /// Maximum walk length before restarting (0 = `20·2^dp_bits`).
    pub max_walk_len: u64,
    /// RNG seed.
    pub seed: u64,
}

impl Default for RhoParams {
    fn default() -> Self {
        Self {
            branches: 32,
            dp_bits: 0,
            negation_map: true,
            max_ops: 0,
            max_walk_len: 0,
            seed: 1,
        }
    }
}

/// Result of a solve.
#[derive(Clone, Debug)]
pub struct RhoResult {
    pub k: BigUint,
    /// Group operations spent in the walks (table setup excluded).
    pub walk_ops: u64,
    /// Group operations spent building the branch table.
    pub setup_ops: u64,
    /// Distinguished points stored.
    pub distinguished_points: usize,
    /// Independent walks started.
    pub walks: u64,
    /// `walk_ops / sqrt(N)`.
    pub s_walk: f64,
}

struct Branch<E> {
    a: BigUint,
    b: BigUint,
    pt: E,
}

/// Solve `q = k·p` in the cyclic subgroup of prime order `n` generated by `p`.
pub fn pollard_rho<G: JacobianGroup>(
    group: &G,
    p: &G::Elem,
    q: &G::Elem,
    n: &BigUint,
    params: &RhoParams,
) -> Result<RhoResult, HgError> {
    if n.is_zero() || n.is_one() {
        return Err(HgError::Unsupported("subgroup order must exceed 1"));
    }
    let mut rng = StdRng::seed_from_u64(params.seed);
    let sqrt_n = n.sqrt();
    let sqrt_f = sqrt_n.to_string().parse::<f64>().unwrap_or(1.0).max(1.0);
    let dp_bits = if params.dp_bits == 0 {
        // About sqrt(sqrt N)/4 points per DP: keeps the table small and walks short.
        ((sqrt_n.bits() as f64 / 2.0).floor() as u32)
            .saturating_sub(2)
            .min(24)
    } else {
        params.dp_bits
    };
    let dp_mask: u64 = if dp_bits == 0 {
        0
    } else {
        (1u64 << dp_bits) - 1
    };
    let max_ops = if params.max_ops == 0 {
        (sqrt_f * 64.0).max(1_000_000.0) as u64
    } else {
        params.max_ops
    };
    let max_walk_len = if params.max_walk_len == 0 {
        20u64 << dp_bits
    } else {
        params.max_walk_len
    };

    let start_ops = group.group_ops();
    // Branch table.
    let mut branches: Vec<Branch<G::Elem>> = Vec::with_capacity(params.branches);
    for _ in 0..params.branches.max(2) {
        let a = random_below(&mut rng, n);
        let b = random_below(&mut rng, n);
        let pt = group.add(&group.scalar_mul(&a, p), &group.scalar_mul(&b, q));
        branches.push(Branch { a, b, pt });
    }
    let setup_ops = group.group_ops() - start_ops;
    let r = branches.len() as u64;

    // Distinguished points: key → (a, b, walk id).
    let mut table: HashMap<u64, (BigUint, BigUint, u64)> = HashMap::new();
    let mut walks = 0u64;
    let walk_start_ops = group.group_ops();

    let neg = params.negation_map;
    // Normalise an element to the ± representative, adjusting (a, b).
    let normalise = |x: G::Elem, a: &mut BigUint, b: &mut BigUint| -> G::Elem {
        if neg && !group.is_negation_representative(&x) {
            *a = (n - &*a) % n;
            *b = (n - &*b) % n;
            group.neg(&x)
        } else {
            x
        }
    };

    loop {
        if group.group_ops() - walk_start_ops > max_ops {
            return Err(HgError::Exhausted("rho walk budget"));
        }
        walks += 1;
        let mut a = random_below(&mut rng, n);
        let mut b = random_below(&mut rng, n);
        let mut x = group.add(&group.scalar_mul(&a, p), &group.scalar_mul(&b, q));
        x = normalise(x, &mut a, &mut b);
        let mut len = 0u64;
        let mut prev_hash = u64::MAX;
        loop {
            len += 1;
            if len > max_walk_len {
                break; // restart from a fresh random point
            }
            let h = group.hash64(&x);
            if h & dp_mask == 0 {
                // Distinguished.
                if let Some((a2, b2, w2)) = table.get(&h) {
                    if *w2 != walks || (*a2 != a && *b2 != b) {
                        if let Some(k) = combine(&a, &b, a2, b2, n) {
                            let check = group.scalar_mul(&k, p);
                            if check == *q {
                                let walk_ops = group.group_ops() - walk_start_ops;
                                return Ok(RhoResult {
                                    k,
                                    walk_ops,
                                    setup_ops,
                                    distinguished_points: table.len(),
                                    walks,
                                    s_walk: walk_ops as f64 / sqrt_f,
                                });
                            }
                        }
                        // Hash collision of distinct points, or useless relation: restart.
                        break;
                    }
                    // Same walk, same point: cycle; restart.
                    break;
                }
                table.insert(h, (a.clone(), b.clone(), walks));
            }
            let j = (h % r) as usize;
            let br = &branches[j];
            let mut na = (&a + &br.a) % n;
            let mut nb = (&b + &br.b) % n;
            let mut nx = group.add(&x, &br.pt);
            nx = normalise(nx, &mut na, &mut nb);
            let nh = group.hash64(&nx);
            if neg && nh == prev_hash {
                // Fruitless 2-cycle: escape by doubling.
                na = (&a * 2u32) % n;
                nb = (&b * 2u32) % n;
                nx = group.double(&x);
                nx = normalise(nx, &mut na, &mut nb);
            }
            prev_hash = h;
            a = na;
            b = nb;
            x = nx;
        }
    }
}

/// From `a P + b Q = a' P + b' Q` get `k = (a − a')/(b' − b) mod N`.
fn combine(a: &BigUint, b: &BigUint, a2: &BigUint, b2: &BigUint, n: &BigUint) -> Option<BigUint> {
    let num = (a + n - a2) % n;
    let den = (b2 + n - b) % n;
    if den.is_zero() {
        return None;
    }
    let inv = mod_inverse(&den, n)?;
    Some((num * inv) % n)
}

/// Modular inverse via the extended Euclidean algorithm (`n` prime here).
pub fn mod_inverse(a: &BigUint, n: &BigUint) -> Option<BigUint> {
    let ab = num_bigint::BigInt::from(a.clone());
    let nn = num_bigint::BigInt::from(n.clone());
    let e = ab.extended_gcd(&nn);
    if !e.gcd.is_one() {
        return None;
    }
    let x = ((e.x % &nn) + &nn) % &nn;
    x.to_biguint()
}

/// Uniform random integer in `[0, n)`.
pub fn random_below(rng: &mut impl RngCore, n: &BigUint) -> BigUint {
    let bits = n.bits();
    let bytes = bits.div_ceil(8) as usize;
    loop {
        let mut buf = vec![0u8; bytes];
        rng.fill_bytes(&mut buf);
        let mut x = BigUint::from_bytes_le(&buf);
        let excess = bytes as u64 * 8 - bits;
        if excess > 0 {
            x >>= 0u32; // no-op; mask below
            let mask = (BigUint::one() << bits) - BigUint::one();
            x &= mask;
        }
        if x < *n {
            return x;
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::highgenus::cantor::HyperellipticCurve;
    use crate::highgenus::fp::Fp;
    use crate::highgenus::poly::Poly;

    #[test]
    fn solves_a_small_hyperelliptic_dlp() {
        // y² = x⁵ + 3x³ + 2x² + x + 1 over F_31; find the order of a random element by brute force.
        let k = Fp::new(31).unwrap();
        let c = HyperellipticCurve::new(k, Poly::from_coeffs(vec![1, 1, 2, 3, 0, 1], &k)).unwrap();
        let mut rng = StdRng::seed_from_u64(9);
        let base = c.random_element(2, &mut rng);
        // Brute-force the order.
        let mut acc = base.clone();
        let mut ord = 1u64;
        while !acc.is_identity() {
            acc = c.add_divisors(&acc, &base);
            ord += 1;
            assert!(ord < 10_000_000);
        }
        // Largest prime factor of ord.
        let mut n = ord;
        let mut largest = 1;
        let mut d = 2;
        while d * d <= n {
            while n.is_multiple_of(d) {
                largest = d;
                n /= d;
            }
            d += 1;
        }
        if n > 1 {
            largest = n;
        }
        let cof = BigUint::from(ord / largest);
        let p = c.scalar_mul(&cof, &base);
        assert!(!p.is_identity());
        let n = BigUint::from(largest);
        let kk = BigUint::from(12345u32) % &n;
        let q = c.scalar_mul(&kk, &p);
        let res = pollard_rho(&c, &p, &q, &n, &RhoParams::default()).unwrap();
        assert_eq!(res.k, kk);
    }
}
