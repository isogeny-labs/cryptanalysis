//! Identities for the factor-base toolkit: canonical JSON, digests, curve IDs,
//! PS1 labels, cell and sweep identifiers.
//!
//! Everything here is byte-compatible with the Python reference tools
//! (`tools/curve_identity.py`, `experiments/pdp-degree-heuristics/toycurve.py`,
//! `experiments/fb-archive/ps1.py`): canonical JSON is
//! `json.dumps(v, sort_keys=True, separators=(",", ":"), ensure_ascii=False)`
//! and floats are rejected.
//!
//! Sorted keys rely on `serde_json::Map` being `BTreeMap`-backed, which holds
//! while the `preserve_order` feature is off (a unit test guards this).
//!
//! # Limitation
//!
//! Python emits arbitrary-size integers as JSON integers. Without the
//! `arbitrary_precision` feature of `serde_json` (not enabled; no new crates),
//! a `Value` number holds at most 64 bits, so the record builders here take
//! `u64`/`i64` and curves with larger coordinates cannot be expressed
//! (they fit for every toy curve with `n <= 63`). Callers holding wider
//! values must supply them already as JSON numbers that fit, or as the
//! string encoding of their own record, which then hashes differently from
//! Python's integer form.

use serde_json::{json, Map, Value};

use crate::hash::sha256::sha256;

/// Top-level manifest keys that are runtime or budget controls and therefore
/// do not enter [`sweep_id`].
pub const SWEEP_ID_EXCLUDED_KEYS: [&str; 5] =
    ["jobs", "budget_seconds", "dir", "resume", "progress"];

fn check_no_floats(v: &Value) -> Result<(), String> {
    match v {
        Value::Number(n) if n.is_f64() => Err(format!(
            "identity records require JSON without floats, found {n}"
        )),
        Value::Array(a) => a.iter().try_for_each(check_no_floats),
        Value::Object(o) => o.values().try_for_each(check_no_floats),
        _ => Ok(()),
    }
}

/// Canonical JSON text: sorted keys, compact separators, UTF-8 (not
/// ASCII-escaped). Errors when the tree contains a float.
pub fn canonical_json(v: &Value) -> Result<String, String> {
    check_no_floats(v)?;
    serde_json::to_string(v).map_err(|e| e.to_string())
}

/// Lowercase hex SHA-256 of raw bytes.
pub fn sha256_hex_bytes(data: &[u8]) -> String {
    hex::encode(sha256(data))
}

/// Lowercase hex SHA-256 of the canonical JSON of `v`.
pub fn sha256_hex(v: &Value) -> Result<String, String> {
    Ok(sha256_hex_bytes(canonical_json(v)?.as_bytes()))
}

/// Lowercase hex BLAKE3 of raw bytes.
pub fn blake3_hex(data: &[u8]) -> String {
    blake3::hash(data).to_hex().to_string()
}

/// The `field` record of a binary polynomial-basis field, as
/// `ToyCurve.field_record` emits it. `modulus_exponents` are the exponents of
/// the modulus polynomial in descending order (for example `[7, 1, 0]`).
pub fn binary_field_record(degree: u32, modulus_exponents: &[u32]) -> Value {
    json!({
        "characteristic": 2,
        "degree": degree,
        "representation": "polynomial_basis",
        "modulus_exponents": modulus_exponents,
        "element_encoding": "unsigned integer; bit i is the coefficient of z^i",
    })
}

/// The `curve` record of a binary curve `y^2 + x*y = x^3 + a2*x^2 + a6`, as
/// `ToyCurve.curve_record` emits it (no `curve_id` key).
#[allow(clippy::too_many_arguments)]
pub fn binary_curve_record(
    a2: u64,
    a6: u64,
    order: u64,
    trace: i64,
    subgroup_order: u64,
    cofactor: u64,
    generator: (u64, u64),
) -> Value {
    json!({
        "model": "y^2 + x*y = x^3 + a2*x^2 + a6",
        "a2": a2,
        "a6": a6,
        "order": order,
        "trace": trace,
        "subgroup_order": subgroup_order,
        "cofactor": cofactor,
        "generator": [generator.0, generator.1],
        "target_group": "prime-order subgroup generated by G",
    })
}

/// The `field` record of a prime field as `experiments/ic-bench/prime_bridge.py`
/// emits it.
pub fn prime_field_record(p: u64) -> Value {
    json!({
        "characteristic": p,
        "degree": 1,
        "representation": "prime field",
        "element_encoding": "unsigned decimal integer",
    })
}

/// The `curve` record of a short Weierstrass curve `y^2 = x^3 + a x + b`
/// over a prime field, with the key set of `prime_bridge.py`.
#[allow(clippy::too_many_arguments)]
pub fn prime_curve_record(
    a: u64,
    b: u64,
    group_order: u64,
    subgroup_order: u64,
    cofactor: u64,
    generator: (u64, u64),
) -> Value {
    json!({
        "model": "short_weierstrass",
        "a": a,
        "b": b,
        "group_order": group_order,
        "subgroup_order": subgroup_order,
        "cofactor": cofactor,
        "generator": [generator.0, generator.1],
        "target_group": "prime-order subgroup generated by G",
    })
}

/// Curve record without any `curve_id` key (the hash input excludes it).
fn without_curve_id(curve: &Value) -> Result<Value, String> {
    let Value::Object(o) = curve else {
        return Err("curve record must be an object".into());
    };
    let mut m: Map<String, Value> = o.clone();
    m.remove("curve_id");
    Ok(Value::Object(m))
}

/// SHA-256 of `{"field": field, "curve": curve-without-curve_id}`
/// (Python `curve_identity()["curve_sha256"]`).
pub fn curve_sha256(field: &Value, curve: &Value) -> Result<String, String> {
    let clean = without_curve_id(curve)?;
    sha256_hex(&json!({"field": field, "curve": clean}))
}

/// EC1 curve ID `EC1<N n | P bits | Q p D n>C<tag>h<12 hex>`, matching
/// `curve_identity()["curve_id"]`. `tag` must match `[a-z][a-z0-9]*`.
pub fn curve_id(field: &Value, curve: &Value, tag: &str) -> Result<String, String> {
    let p = field
        .get("characteristic")
        .and_then(Value::as_u64)
        .filter(|p| *p >= 2)
        .ok_or("characteristic must be an integer >= 2 (u64)")?;
    let n = field
        .get("degree")
        .and_then(Value::as_u64)
        .filter(|n| *n >= 1)
        .ok_or("degree must be a positive integer")?;
    let mut chars = tag.chars();
    let tag_ok = chars.next().is_some_and(|c| c.is_ascii_lowercase())
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit());
    if !tag_ok {
        return Err(format!("invalid readable curve tag {tag:?}"));
    }
    let prefix = if p == 2 {
        format!("N{n}")
    } else if n == 1 {
        format!("P{}", 64 - p.leading_zeros())
    } else {
        format!("Q{p}D{n}")
    };
    let sha = curve_sha256(field, curve)?;
    Ok(format!("EC1{prefix}C{tag}h{}", &sha[..12]))
}

/// `PS1N<n>C<tag>fb<B>PDP<m><solver>h<12hex>` as `ps1.cell_manifest` forms it:
/// the hash input is `{"factor_base_sha256": ..., "point_decomposition": pdp}`.
/// `fb_points` is the number of distinct usable points before folding.
pub fn ps1_label(
    n: u64,
    tag: &str,
    fb_points: u64,
    m: u64,
    solver: &str,
    factor_base_sha256: &str,
    pdp_record: &Value,
) -> Result<String, String> {
    if tag.is_empty()
        || !tag
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
    {
        return Err(format!("invalid curve tag {tag:?}"));
    }
    if solver.is_empty()
        || !solver
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
    {
        return Err(format!("invalid solver name {solver:?}"));
    }
    let digest = sha256_hex(&json!({
        "factor_base_sha256": factor_base_sha256,
        "point_decomposition": pdp_record,
    }))?;
    Ok(format!(
        "PS1N{n}C{tag}fb{fb_points}PDP{m}{solver}h{}",
        &digest[..12]
    ))
}

/// SHA-256 of the canonical JSON array of the sorted `[x, y]` lowercase-hex
/// pairs (the `enumerated_set_sha256` convention). Input order is irrelevant.
pub fn point_set_sha256(points: &[(String, String)]) -> String {
    let mut pairs: Vec<(String, String)> = points
        .iter()
        .map(|(x, y)| (x.to_ascii_lowercase(), y.to_ascii_lowercase()))
        .collect();
    pairs.sort();
    let arr: Vec<Value> = pairs.into_iter().map(|(x, y)| json!([x, y])).collect();
    // Strings only, so canonicalisation cannot fail.
    sha256_hex(&Value::Array(arr)).unwrap_or_default()
}

/// Sweep identifier: first 12 hex of the SHA-256 of the canonical manifest with
/// the top-level keys in [`SWEEP_ID_EXCLUDED_KEYS`] and any `sweep_id` key
/// removed.
pub fn sweep_id(manifest: &Value) -> Result<String, String> {
    let Value::Object(o) = manifest else {
        return Err("manifest must be an object".into());
    };
    let mut m = o.clone();
    for k in SWEEP_ID_EXCLUDED_KEYS {
        m.remove(k);
    }
    m.remove("sweep_id");
    Ok(sha256_hex(&Value::Object(m))?[..12].to_string())
}

/// Lowercase slug over `[a-z0-9-]`: other characters become `-`, runs of `-`
/// collapse, leading and trailing `-` are trimmed.
pub fn slug(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars().flat_map(char::to_lowercase) {
        if c.is_ascii_lowercase() || c.is_ascii_digit() {
            out.push(c);
        } else if !out.ends_with('-') {
            out.push('-');
        }
    }
    out.trim_matches('-').to_string()
}

/// Cell identifier `<family>-<params-slug>-m<m>-l<l>-<8hex>` where the 8 hex
/// are the first digits of the canonical recipe digest. An empty parameter
/// slug is omitted.
pub fn cell_id(
    family: &str,
    params: &str,
    m: u32,
    l: u32,
    recipe: &Value,
) -> Result<String, String> {
    let digest = sha256_hex(recipe)?;
    let p = slug(params);
    let mid = if p.is_empty() {
        String::new()
    } else {
        format!("{p}-")
    };
    Ok(format!("{}-{mid}m{m}-l{l}-{}", slug(family), &digest[..8]))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn toy() -> (Value, Value) {
        (
            binary_field_record(7, &[7, 1, 0]),
            binary_curve_record(1, 5, 134, -5, 67, 2, (3, 91)),
        )
    }

    #[test]
    fn canonical_matches_python() {
        let v = json!({"b": [1, "é\n\"x"], "a": null, "c": true, "d": -7});
        assert_eq!(
            canonical_json(&v).unwrap(),
            "{\"a\":null,\"b\":[1,\"é\\n\\\"x\"],\"c\":true,\"d\":-7}"
        );
    }

    #[test]
    fn rejects_floats() {
        assert!(canonical_json(&json!({"a": [1.5]})).is_err());
        assert!(sha256_hex(&json!(0.0)).is_err());
    }

    #[test]
    fn keys_are_sorted_btreemap() {
        let mut m = Map::new();
        m.insert("z".into(), json!(1));
        m.insert("a".into(), json!(2));
        assert_eq!(
            canonical_json(&Value::Object(m)).unwrap(),
            "{\"a\":2,\"z\":1}"
        );
    }

    /// Pin computed once with `python3 -I` importing `tools/curve_identity.py`
    /// (`curve_identity`) on the same field/curve records.
    #[test]
    fn python_pin() {
        let (f, c) = toy();
        assert_eq!(
            canonical_json(&json!({"field": f, "curve": c}))
                .unwrap()
                .len(),
            PIN_LEN
        );
        assert_eq!(curve_sha256(&f, &c).unwrap(), PIN_SHA);
        assert_eq!(curve_id(&f, &c, "kb1").unwrap(), PIN_ID);
        assert_eq!(sha256_hex(&f).unwrap(), PIN_FIELD_SHA);
    }

    #[test]
    fn curve_id_format_and_ignores_curve_id_key() {
        let (f, mut c) = toy();
        let id = curve_id(&f, &c, "kb1").unwrap();
        c["curve_id"] = json!("whatever");
        assert_eq!(curve_id(&f, &c, "kb1").unwrap(), id);
        assert!(id.starts_with("EC1N7Ckb1h") && id.len() == "EC1N7Ckb1h".len() + 12);
        assert!(curve_id(&f, &c, "Bad").is_err());
        let pf = prime_field_record(1_000_003);
        let pc = prime_curve_record(1, 2, 1_000_100, 1_000_100, 1, (3, 4));
        assert!(curve_id(&pf, &pc, "gen")
            .unwrap()
            .starts_with("EC1P20Cgenh"));
    }

    #[test]
    fn ps1_label_shape() {
        let l = ps1_label(
            11,
            "kb1",
            24,
            3,
            "sat",
            &"ab".repeat(32),
            &json!({"m": 3, "solver": "sat"}),
        )
        .unwrap();
        let ok = l.starts_with("PS1N11Ckb1fb24PDP3sath")
            && l.len() == "PS1N11Ckb1fb24PDP3sath".len() + 12
            && l[l.len() - 12..].chars().all(|c| c.is_ascii_hexdigit());
        assert!(ok, "{l}");
        assert_eq!(l, PIN_PS1);
    }

    #[test]
    fn point_set_is_order_and_case_independent() {
        let a = vec![("B".to_string(), "1".to_string()), ("a".into(), "2".into())];
        let b = vec![("a".to_string(), "2".to_string()), ("b".into(), "1".into())];
        assert_eq!(point_set_sha256(&a), point_set_sha256(&b));
        assert_eq!(
            point_set_sha256(&b),
            sha256_hex_bytes(br#"[["a","2"],["b","1"]]"#)
        );
    }

    #[test]
    fn slug_rules() {
        assert_eq!(slug("Gp Scaled__K=3,"), "gp-scaled-k-3");
        assert_eq!(slug("--"), "");
    }

    #[test]
    fn sweep_id_ignores_budget_keys() {
        let a = json!({"families": ["a"], "dims": [3], "jobs": 2, "budget_seconds": 5});
        let b = json!({"families": ["a"], "dims": [3], "jobs": 8, "resume": true, "dir": "/x",
                       "sweep_id": "zzz"});
        let c = json!({"families": ["b"], "dims": [3]});
        assert_eq!(sweep_id(&a).unwrap(), sweep_id(&b).unwrap());
        assert_ne!(sweep_id(&a).unwrap(), sweep_id(&c).unwrap());
        assert_eq!(sweep_id(&a).unwrap().len(), 12);
    }

    #[test]
    fn cell_id_shape() {
        let id = cell_id("gp-scaled", "l=3", 2, 3, &json!({"f": 1})).unwrap();
        assert!(id.starts_with("gp-scaled-l-3-m2-l3-"), "{id}");
        assert_eq!(id.len(), "gp-scaled-l-3-m2-l3-".len() + 8);
    }

    #[test]
    fn digests_of_bytes() {
        assert_eq!(
            sha256_hex_bytes(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(blake3_hex(b"").len(), 64);
    }

    const PIN_LEN: usize = 368;
    const PIN_SHA: &str = "e2dcb29cee1f7c35e2f617aabbafa3f9b08f7f8332dfd22c6a25b66dc44a9e0b";
    const PIN_ID: &str = "EC1N7Ckb1he2dcb29cee1f";
    const PIN_FIELD_SHA: &str = "67efb9098fba05cddd665e3d714402bbc7c330d57daa1ecf5fe521727b4466b7";
    const PIN_PS1: &str = "PS1N11Ckb1fb24PDP3sathad775470256c";
}
