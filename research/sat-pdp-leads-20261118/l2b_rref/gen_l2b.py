#!/usr/bin/env python3
"""L2b: base CNF (identical to L2) plus a companion CNF that adds the fully
row-reduced (RREF over GF(2)) XOR rows of the same system as redundant
prefix-parity chains with fresh variables, the leaf-independent part of the
extension variables in lead E's short certificates
(crypto:research/sat_smt_leads_20261115/E-scan-certificate-proof, xproof.py:
"rows ... with prefix-parity variables P[j] = v_0 + .. + v_j").

For each RREF row with variables v_0 < .. < v_k and constant c:
  P_0 = v_0;  P_j = P_{j-1} XOR v_j (fresh P_j, 4 clauses each);  P_k = c (unit).
Rows identical to an original XOR row are skipped (already present). The base
part is generated by ../l2_sbva/gen_instances.py's code path, so the base files
are byte-identical to L2's (checked against its manifest when present).

Output: <out>/<name>.cnf (base) and <out>/<name>.rref.cnf, manifest.json.
"""
import argparse, hashlib, json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../l2_sbva"))
from gen_instances import xor_to_cnf  # noqa: E402


def rref(rows):
    """rows: list of int bitmasks (bit v = variable v, bit 0 = constant). Fully reduced."""
    piv = {}  # pivot var -> row
    for r in rows:
        for p, pr in piv.items():
            if r >> p & 1:
                r ^= pr
        if r >> 1 == 0:
            if r & 1:
                raise ValueError("inconsistent XOR system")
            continue
        p = r.bit_length() - 1  # highest variable as pivot
        for q in list(piv):
            if piv[q] >> p & 1:
                piv[q] ^= r
        piv[p] = r
    return list(piv.values())


def chain(vs, rhs, nv):
    cls = []
    prev = vs[0]
    for v in vs[1:]:
        nv += 1
        p = nv  # p = prev XOR v
        cls += [[-p, prev, v], [-p, -prev, -v], [p, -prev, v], [p, prev, -v]]
        prev = p
    cls.append([prev] if rhs else [-prev])
    return cls, nv


def emit(path, nv, cls):
    body = f"p cnf {nv} {len(cls)}\n" + "".join(" ".join(map(str, c)) + " 0\n" for c in cls)
    with open(path, "w") as f:
        f.write(body)
    return hashlib.sha256(body.encode()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--crypto", default=os.path.join(HERE, "../../../../crypto"))
    ap.add_argument("--out", required=True)
    ap.add_argument("--l", type=int, nargs="+", default=[3, 4])
    ap.add_argument("--enc", nargs="+", default=["plain", "dual"])
    ap.add_argument("--seed-base", type=int, default=2026111500,
                    help="cell seed = seed_base + l (L2/L2b used 2026111500)")
    ap.add_argument("--n-non", type=int, default=8)
    ap.add_argument("--n-dec", type=int, default=4)
    a = ap.parse_args()
    sys.path.insert(0, os.path.join(os.path.abspath(a.crypto),
                                    "research/sat_smt_leads_20261115/A-dualrail-m4"))
    import dr4  # noqa: E402
    commit = subprocess.run(["git", "-C", a.crypto, "rev-parse", "HEAD"],
                            capture_output=True, text=True).stdout.strip()
    os.makedirs(a.out, exist_ok=True)
    man = {"crypto_commit": commit, "seed_base": a.seed_base, "instances": []}
    for l in a.l:
        cell = dr4.Cell4(l, a.seed_base + l)
        non, dec = cell.targets(a.n_non, a.n_dec)
        tg = [(i, R, False) for i, R in enumerate(non)] + [(a.n_non + i, R, True) for i, R in enumerate(dec)]
        for idx, R, isdec in tg:
            S = dr4.System4(cell, R)
            for enc in a.enc:
                nv, clauses, xors = S.render(enc)
                base = [list(c) for c in clauses]
                nvb = nv
                for vs, rhs in xors:
                    c2, nvb = xor_to_cnf(vs, bool(rhs), nvb)
                    base += c2
                name = f"l{l}_{enc}_t{idx:02d}"
                hb = emit(os.path.join(a.out, name + ".cnf"), nvb, base)
                # RREF of the original XOR rows (over the original variables only)
                orig = set()
                rows = []
                for vs, rhs in xors:
                    r = (1 if rhs else 0)
                    for v in vs:
                        r ^= 1 << v
                    rows.append(r); orig.add(r)
                red = [r for r in rref(rows) if r not in orig]
                ext = list(base); nve = nvb; added_len = 0
                for r in red:
                    vs = [v for v in range(1, r.bit_length()) if r >> v & 1]
                    c2, nve = chain(vs, bool(r & 1), nve)
                    ext += c2; added_len += len(vs)
                he = emit(os.path.join(a.out, name + ".rref.cnf"), nve, ext)
                man["instances"].append({"file": name + ".cnf", "rref_file": name + ".rref.cnf",
                                         "l": l, "n": cell.n, "enc": enc, "idx": idx,
                                         "decomposable": isdec, "vars": nvb, "clauses": len(base),
                                         "rref_vars": nve, "rref_clauses": len(ext),
                                         "xor_rows": len(rows), "rref_rows_added": len(red),
                                         "rref_mean_row_len": added_len / len(red) if red else 0,
                                         "sha256": hb, "rref_sha256": he})
                print(name, nvb, len(base), "->", nve, len(ext), "rows", len(rows), "added", len(red), flush=True)
    with open(os.path.join(a.out, "manifest.json"), "w") as f:
        json.dump(man, f, indent=1)


if __name__ == "__main__":
    main()
